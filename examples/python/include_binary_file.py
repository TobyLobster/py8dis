"""include_binary_file(): the 8 bytes at $0e05, between "Hello" and " world",
are the same as the file orig/include_binary_data.bin, so they're written
as an 'include this file' directive (e.g. beebasm's incbin) rather than as
data. py8dis checks that the file's contents match the bytes there. There's
no code: the rest of the file is data, and its strings are found by
autostring()."""

from commands import *

# Output settings (see docs/configuration.md): no comments saying where each
# label is used from, or giving the character an immediate value stands for,
# and no list of the auto-generated labels at the end
config.set_label_references(False)
config.set_hex_dump(True)
config.set_show_autogenerated_labels(False)
config.set_show_cpu_state(False)
config.set_show_char_literals(False)
config.set_show_all_labels(False)

load(0x0e00, "orig/include_binary_file.orig", "6502")

include_binary_file(0x0e05, "orig/include_binary_data.bin")

go()
