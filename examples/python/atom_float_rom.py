"""The Acorn Atom's floating point ROM (#D000-#DFFF), as a test on a real
program, with acorn.atom(). The names and comments are Toby Nelson's.

BASIC passes the statements and functions it doesn't know to this ROM,
through the addresses at #D002 and #D004 (see atom_basic_rom.py). Its
keyword table (at #D006) is each keyword then the address of its routine,
high byte first. A statement it doesn't know either goes on to a ROM at
#E000 or the utility ROM at #A000, if one is there."""

