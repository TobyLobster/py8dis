def series(a):
    num_coefficients = get_u8_binary(a)+1
    byte(a, 1)
    comment(a, "Number of coefficients - 1", inline=True)
    for n in range(num_coefficients):
        byte(a+1+5*n, 5)

def skip(a):
    global skip_counter

    label(a, "skip"+str(skip_counter))
    skip_counter += 1

def jump_addr(addr, lab):
    byte(addr)
    byte(addr+1)
    expr(addr, make_hi(lab))
    expr(addr+1, make_lo(lab))

