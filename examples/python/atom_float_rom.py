def my_label_maker(d):
    # This example replaces any instances of one label name with another,
    # when found between a range of binary addresses.
    if d.in_range(0xdf52, 0xdfff):
        d.replace("float8A_man1", "x_coord_low")
        d.replace("float8A_man2", "x_coord_high")
        d.replace("float8A_man3", "y_coord_low")
        d.replace("float8A_man4", "y_coord_high")
        d.replace("float8A_rounding", "mode_of_operation")
        d.replace("float8B_sign", "colour_screen_address_low")
        d.replace("float8B_overflow", "colour_screen_address_high")

set_label_maker_hook(my_label_maker)

