"""
Label making data

A LabelMakingData holds a suggested name for a label at one place where the
label is used or defined, with what's known about that place. It's how a
name is passed through the stages of choosing it (see
disassembly.label_maker()): disassembly.suggest_label_name() makes one, the
CPU's label_maker() may change its name (e.g. to 'return_1'), and then the
control file's label maker hook may change its name or move (see
set_label_maker_hook() and docs/snippets-and-hooks.md).
"""

from binaryaddrtype import BinaryAddrType

class LabelMakingData:
    """A suggested name for a label, where it's used or defined.

    'name' is the name (a simple name, or an expression, e.g. 'table+1').

    'defined_as_runtime_addr' is the label's value: the runtime address it
    names. 'defined_in_move_id' is the move its definition belongs to, i.e.
    the move ID the name is added to the label for (None for the base move).

    'binary_addr' is where the label is used (e.g. the address of the
    operand of 'lda label') or where it's defined, as 'binary_addr_type'
    says (see BinaryAddrType).

    'is_autogenerated' is True for a name py8dis made up (e.g. 'l1234'),
    and 'is_expression' is True if the name is one of the label's
    expressions."""

    def __init__(self,
                 name,
                 defined_as_runtime_addr,
                 defined_in_move_id,
                 binary_addr,
                 binary_addr_type: BinaryAddrType,
                 is_autogenerated,
                 is_expression):
        self.name = name

        # Label definition
        self.defined_as_runtime_addr = defined_as_runtime_addr        # Must have a value
        self.defined_in_move_id      = defined_in_move_id             # None means the base move
        self.binary_addr_type        = binary_addr_type
        self.binary_addr             = binary_addr

        self.is_autogenerated = is_autogenerated
        self.is_expression    = is_expression

        # For an optional label's name that's relative to another address's
        # (e.g. 'tape_buffer+1'): (that address, whether its label can be
        # defined inline), so it can be given a label if this name is used
        self.optional_base    = None

    def in_range(self, start, end):
        """Checks if the label is used within the given binary address range

        (from start up to, but not including, end). For a label hook, e.g.
        to rename a label only where some routine uses it."""
        if self.binary_addr == None:
            return False
        return start <= self.binary_addr < end

    def in_move(self, defined_in_move_id):
        """Checks if the label is defined in the given move"""
        return self.defined_in_move_id == defined_in_move_id

    def replace(self, from_, to):
        """Change the label name from one string ('from_') to another ('to'), or set the label name at the given binary address ('from_') where it is used

        Returns True if the name was changed. (For a label hook, see
        docs/snippets-and-hooks.md.)"""
        if self.name == from_:
            # 'from_' name matched, replace with 'to' name
            self.name = to
            return True
        elif isinstance(from_, int) and (from_ == self.binary_addr) and (self.binary_addr != None):
            # 'from_' address matched the binary address, replace with 'to' name
            self.name = to
            return True
        return False

    def copy(self):
        """A copy, e.g. to see whether a label hook changed the suggestion
        (see disassembly._label_maker()). (optional_base isn't copied.)"""
        return LabelMakingData(
            name=self.name,
            defined_as_runtime_addr=self.defined_as_runtime_addr,
            defined_in_move_id=self.defined_in_move_id,
            binary_addr=self.binary_addr,
            binary_addr_type=self.binary_addr_type,
            is_autogenerated=self.is_autogenerated,
            is_expression=self.is_expression
        )

    def __str__(self):
        return "label: {0} at runtime: {1} in move_id: {2} autogenerated:{3} expression:{4}".format(self.name, hex(self.defined_as_runtime_addr), self.defined_in_move_id, self.is_autogenerated, self.is_expression)

    def __repr__(self):
        return self.__str__()
