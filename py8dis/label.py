"""
Label

A label is a runtime address that is, or may be, given a name in the output.
One Label object holds everything known about the names for one address
(the session's labels are kept by labelmanager.py, one per address):

    explicit names      ordinary ('global') names, e.g. 'print_loop', used
                        wherever the address is referred to. A name is
                        either given (by the control file, e.g. with label()
                        or entry(), or an optional label's name once it's
                        used) or auto-generated (made up by py8dis, e.g.
                        'l1234', 'loop_c2002', 'return_1'). A name can have a
                        priority, which puts it first among the names at its
                        address (as pydis_start does).
    local labels        names used only where the address is referred to
                        from a range of binary addresses (see local_label()).
                        There they take precedence over the explicit names.
    expressions         e.g. 'table+1' (see expr_label()), written where the
                        address is referred to, but never defined.

Each of these is held for a move ID (see labelmanager.py for why). A Label
also records the binary locations that refer to it ('references'), and
whether it can be defined inline ('definable_inline').

How a name is chosen

Most names are chosen after tracing, the first time the label is used in
the output (see disassembly.get_label(), LabelRef and fix_label_names()).
disassembly.suggest_label_name() picks a name the label already has (a
local label for where it's used, then an explicit name, then an
expression), or an optional label's name, or else makes one up. Then the
CPU and the control file's label maker hook can change it (see
disassembly.label_maker()). A simple name chosen this way is added to the
label as an explicit name, so it's defined, and used again next time.

Where the names are defined

Each explicit name is defined once in the output ('emitted' records when it
has been), in one of two ways:

    inline              at the label's address in the main disassembly, e.g.
                        '.print_loop' for beebasm, or 'print_loop:' for
                        z88dk (see gather_inline_label_definitions()). If the
                        address is inside a multi-byte instruction or data
                        item, the name is instead defined just before the
                        item, relative to a label at its start, e.g. 'l1235 =
                        c1234+1'.
    'name = value'      in the "Memory locations" list at the top of the
                        output (see gather_explicit_definitions()): every
                        name not defined inline by the time the main
                        disassembly has been made. That's mainly the names
                        of addresses outside the loaded data (e.g. OS calls,
                        or zero page), and of labels that can't be defined
                        inline (definable_inline is False, e.g. for hardware
                        registers, or see
                        disassembly.define_forward_zero_page_labels_first()).

(A name for a move that isn't output at the label's address is defined
inline in another move that is, if there is one: see
gather_inline_label_definitions().)

Local label names are always defined in the "Memory locations" list (each
name once, see gather_explicit_definitions()).
"""

import collections
import memorymanager
import movemanager
import session
import disassembly
import config
import utils
from memorymanager import BinaryAddr, RuntimeAddr
from binaryaddrtype import BinaryAddrType

_empty_set = frozenset()

class Label:
    """The names for one runtime address (see the module docstring), and
    the places that refer to it.

    'explicit_names', 'local_labels' and 'expressions' are each a
    dictionary from move ID to a list (of ExplicitName, LocalLabelName and
    expressions respectively), in the order they were added. (They're
    defaultdicts, so looking up a move ID adds an empty list for it.)"""

    class ExplicitName:
        """One of a label's explicit names (see the module docstring).

        'text' is the name. 'emitted' is True once it has been defined in
        the output (inline or as 'name = value'), so it's only defined once.
        'is_autogenerated' is True for a name py8dis made up (e.g. 'l1234',
        or pydis_start), rather than one given.
        'priority', if not None, puts the name before names without one at
        the same address (lowest first).

        'order' says when the name was added to the label (0 for the first),
        which is part of the order the label's names are output in (see
        definition_order())."""
        def __init__(self, name, *, is_autogenerated, priority=None, order=0):
            self.text = name
            self.emitted = False
            self.priority = priority
            self.is_autogenerated = is_autogenerated
            self.order = order

            # Where the name is defined in the output, once it is (for the
            # JSON output): 'inline', 'relative' (as an offset from the label
            # at the start of the item it's inside) or 'memory_locations'.
            # For an inline or relative definition, 'defined_at' is the
            # binary location it's output at.
            self.definition = None
            self.defined_at = None

        def definition_order(self):
            """The order names at the same address are output in, wherever
            they're defined (inline, or as 'name = value' at the top): names
            with a priority first (lowest first), then the order they were
            added to the label (e.g. the order of label() calls, then names
            chosen by py8dis in the order it chose them)."""
            return (float('inf') if self.priority is None else self.priority, self.order)

        def __str__(self):
            return self.text + " (Emitted: " + str(self.emitted) + ")"

        def __repr__(self):
            return self.__str__()

    class LocalLabelName:
        """One of a label's local names (see local_label()): `name` is used
        for the label where it's referred to from binary addresses
        `start_addr` up to (but not including) `end_addr`.

        `output_name` is the name actually used in the output. It is the
        same as `name` unless that name is also used for a different
        address (see labelmanager.assign_local_label_output_names()).

        `heading` is the heading it's defined under in the "Memory
        locations" list, if not its address's memory region's (see
        disassembly.memory_location_definitions()), or None."""
        def __init__(self, name, start_addr, end_addr, heading=None):
            self.name = name
            self.output_name = name
            self.start_addr = start_addr
            self.end_addr = end_addr
            self.heading = heading

        def __str__(self):
            return "{0} (between {1} and {2})".format(self.name, hex(self.start_addr), hex(self.end_addr))

        def __repr__(self):
            return self.__str__()

    def __init__(self, runtime_addr):
        """Make a label with no names for the runtime address. (The
        session's labels dictionary makes one the first time an address is
        looked up in it, see labelmanager.Labels.)"""
        self.runtime_addr = RuntimeAddr(runtime_addr)

        # Remember the relevant active_move_ids in operation at this point of label creation.
        # These are used to later 'best guess' in which move the label should be output.
        # (i.e. the moves that cover the address, among those of any 'with
        # move(...):' blocks the label is made in, see
        # cpu.generate_references())
        relevant_move_ids = movemanager.move_ids_for_runtime_addr(self.runtime_addr)
        self.relevant_active_move_ids = [x for x in session.current().moves.active_move_ids[:] if x in relevant_move_ids]

        self.references = []         # Holds the binary locations that reference this label

        # `local_labels` stores a list of objects of class LocalLabelName
        # for each move_id, as created by `add_local_label()`
        self.local_labels = collections.defaultdict(list)

        # `explicit_names` holds lists since we want to remember the
        # order user-added names were provided.
        self.explicit_names = collections.defaultdict(list)

        # Non-simple names (expressions, e.g. 'table+1', as strings or
        # expression trees) go in a different list
        self.expressions = collections.defaultdict(list)


        # By default, allow label to be defined inline. (False makes all its
        # names be defined as 'name = value' in the "Memory locations" list
        # instead.)
        self.definable_inline = True

    def add_reference(self, reference_binary_loc):
        """Record that the instruction or data at the binary location refers
        to this label's address. (Done while tracing; see
        cpu.generate_references() for how these are used.)"""
        assert isinstance(reference_binary_loc, movemanager.BinaryLocation)
        self.references.append(reference_binary_loc)

    def is_only_an_expression(self):
        """Whether the label has expressions but no explicit or local names,
        so it's never defined in the output. (classification.autostring()
        doesn't end a string at such a label.)"""
        return not self.explicit_names and not self.local_labels and self.expressions

    def all_names_by_move_id(self):
        """Return all label names and expressions for this label for each move_id.
           Used for the frequency usage output

        (The table of label references at the end of the output, see
        cpu.add_reference_frequency_table().) As {move ID: set of names}, with
        local labels by their output names."""

        result = collections.defaultdict(set)

        # Add all local names
        for move_id, local_labels in self.local_labels.items():
            for local_label in local_labels:
                result[move_id].add(local_label.output_name)

        for move_id, name_list in self.explicit_names.items():
            for name in name_list:
                result[move_id].add(name.text)

        # Add expressions
        for move_id, expression_list in self.expressions.items():
            result[move_id].update(expression_list)
        return result

    def all_names(self):
        """Return all label names and expressions for this label

        (As a set, for every move ID, with each local label's name and
        output name.) Used to avoid adding a name twice."""

        result = set()

        # Add all local names
        for local_labels in self.local_labels.values():
            for local_label in local_labels:
                result.add(local_label.name)
                result.add(local_label.output_name)

        for name_list in self.explicit_names.values():
            for name in name_list:
                result.add(name.text)

        # Add expressions
        for expression_list in self.expressions.values():
            result.update(expression_list)
        return result

    def get_already_emitted_name(self):
        """Return an already defined label name

        (The first explicit name, in move ID order, that has been defined in
        the output so far), or None if there isn't one. See
        disassembly.get_emitted_label()."""

        # Add explicit name
        for name_list in self.explicit_names.values():
            for name in name_list:
                if name.emitted:
                    return name.text

        # (Local labels and expressions don't count)
        return None

    def description(self):
        """Return all label names and expressions for this label as a descriptive string

        e.g. 'temp (local), print_loop (explicit), table+1 (expression)',
        for debugging (see __str__())."""

        result = ""

        # Add all local names
        for local_labels in self.local_labels.values():
            for local_label in local_labels:
                result += local_label.output_name + " (local), "

        for name_list in self.explicit_names.values():
            for name in name_list:
                result += name.text + " (explicit), "

        # Add expressions
        for expression_list in self.expressions.values():
            for expr in expression_list:
                result += expr + " (expression), "
        if result.endswith(", "):
            result = result[0:-2]
        return result

    def add_explicit_name(self, name, move_id, *, is_autogenerated, priority=None):
        """Add a simple named label

        i.e. an explicit name (see ExplicitName) for the move ID (the base
        move if it's None). 'name' must be a simple name, not an expression.
        Nothing happens if the label already has the name (see below)."""

        if move_id is None:
            move_id = movemanager.BASE_MOVE_ID

        assert disassembly.is_simple_name(name)
        assert movemanager.is_valid_move_id(move_id)

        # A name is only added once, for one move ID, even if it's given
        # for another, since an assembler wouldn't accept two definitions.
        # (So if two moves both have code at the same runtime address, e.g.
        # both with 'bne &905', only one of them gets the name; the other
        # could be given a name of its own, e.g. with a suffix.)
        if name not in self.all_names():
            order = sum(len(names) for names in self.explicit_names.values())
            self.explicit_names[move_id].append(self.ExplicitName(name, is_autogenerated=is_autogenerated, priority=priority, order=order))

    def add_local_label(self, name, start_addr, end_addr, move_id, heading=None):
        """Add a local label

        i.e. a name used where the label is referred to from binary addresses
        start_addr up to end_addr (see LocalLabelName), for the move ID (the
        base move if it's None). Unlike add_explicit_name(), the same name
        can be added more than once, for different ranges."""

        if move_id is None:
            move_id = movemanager.BASE_MOVE_ID

        assert disassembly.is_simple_name(name)
        assert movemanager.is_valid_move_id(move_id)

        self.local_labels[move_id].append(self.LocalLabelName(name, start_addr, end_addr, heading))

    def local_label_headings(self):
        """{output name: heading} for the local labels with a heading of
        their own (see LocalLabelName)."""
        return {local.output_name: local.heading for locals in self.local_labels.values() for local in locals if local.heading is not None}

    def add_expression(self, s, move_id, *, force=True):
        """Add an expression to use when referencing a runtime address

        (e.g. 'table+1', from expr_label()), for the move ID. With 'force'
        it's added even if the label already has it (or a name the same);
        otherwise it's only added if it's new."""

        assert not disassembly.is_simple_name(s)
        assert movemanager.is_valid_move_id(move_id)

        if force or (s not in self.all_names()):
            self.expressions[move_id].append(s)

    def gather_explicit_definitions(self):
        """The names to define explicitly ('name = value', in the "Memory
        locations" list at the top of the output): the explicit names not
        output where the label is (in the order they're output, see
        ExplicitName.definition_order()), then the local label names (in the
        order they were added: by move ID, then the order of local_label()
        calls). The explicit names are marked as output.

        Called by disassembly.memory_location_definitions(), once the main
        disassembly has been made, so the names left are those that weren't
        defined inline.

        (We don't invoke the label hook or anything here: if a name got
        *used* for the label at some point, it was added to the label, so we
        know to output it here.)"""

        gathered = []
        for name_list in self.explicit_names.values():
            for name in name_list:
                if not name.emitted:
                    gathered.append(name)
                    name.emitted = True
                    name.definition = "memory_locations"
        result = [name.text for name in sorted(gathered, key=lambda name: name.definition_order())]

        # (A local label used in several ranges is only defined once.)
        for move_id in sorted(self.local_labels):
            for local_label in self.local_labels[move_id]:
                if local_label.output_name not in result:
                    result.append(local_label.output_name)
        return result

    @property
    def emit_opportunities(self):
        """The set of move_ids that are output at this label's address.

        i.e. the moves in which the main disassembly has a place where a
        name for this address could be defined inline (see
        disassembly.emit()).

        (These are recorded in the session's labels.emit_opportunities for every
        address, rather than in each Label, so that there's no need to create
        a Label object for every address in the binary.)"""

        import labelmanager
        return session.current().labels.emit_opportunities.get(self.runtime_addr, _empty_set)

    def gather_inline_label_definitions(self, emit_addr, binary_loc):
        """Get a list of the labels in a move_id as a list of strings.

        i.e. the inline definitions (as text for the assembler) of the
        names not yet defined, to output at 'binary_loc' in the main
        disassembly, whose runtime address is 'emit_addr': the label's own
        address, or the start of the instruction or data item the label's
        address is inside (see gather_inline_label_definitions_for_move_id()).
        The names for binary_loc's move are defined, and perhaps others (see
        below). The names defined are marked as output. Called (via
        output.InlineLabelDefinitions) as the main disassembly is made."""

        assert movemanager.is_valid_move_id(binary_loc.move_id)

        # Emit any definitions for this move_id.
        result = self.gather_inline_label_definitions_for_move_id(emit_addr, binary_loc, binary_loc.move_id)

        # Definitions for move IDs which will never get an opportunity
        # to be emitted inline in their preferred move ID (because that
        # move doesn't cover this label's address) are emitted in the
        # lowest-numbered move ID they can be emitted inline for.
        if (len(self.emit_opportunities) > 0) and (binary_loc.move_id == min(self.emit_opportunities)):
            leftover_move_ids = set(self.explicit_names.keys()) - self.emit_opportunities
            for move_id in sorted(leftover_move_ids):
                assert movemanager.is_valid_move_id(move_id)
                result.extend(self.gather_inline_label_definitions_for_move_id(emit_addr, binary_loc, move_id))
        return result

    def gather_inline_label_definitions_for_move_id(self, emit_addr, binary_loc, names_move_id):
        """Get a list of the inline label definitions for the names in
        `names_move_id` as a list of strings, for output at `binary_loc`.

        Each name not yet output is defined, in definition_order(): at the
        label's own address with the assembler's inline_label() (e.g.
        '.loop' for beebasm), or, if `emit_addr` is before it (the label is
        inside an instruction or data item starting at emit_addr), with
        explicit_label() relative to a label at emit_addr, e.g. 'l1235 =
        c1234+1'. That label is made with get_label(), so it may be named
        here. Nothing is defined if the label isn't definable_inline (its
        names are left for the "Memory locations" list)."""
        assembler = config.get_assembler()
        result = []
        assert emit_addr <= self.runtime_addr
        offset = self.runtime_addr - emit_addr

        if not self.definable_inline:
            return result

        filtered_and_sorted = sorted(
            [item for item in self.explicit_names[names_move_id] if not item.emitted],
            key=lambda name: name.definition_order())

        for name in filtered_and_sorted:
            if disassembly.is_simple_name(name.text):
                if offset == 0:
                    result.append(assembler.inline_label(name.text))
                    name.definition = "inline"
                else:
                    # (Relative to the label at the start of the item, e.g.
                    # 'l1235 = c1234+1')
                    label = disassembly.get_label(emit_addr, binary_loc.binary_addr, move_id=binary_loc.move_id, binary_addr_type=BinaryAddrType.BINARY_ADDR_IS_AT_LABEL_DEFINITION)
                    result.append(assembler.explicit_label(name.text, label, offset))
                    name.definition = "relative"
                name.defined_at = binary_loc

            name.emitted = True

        return result

    def __str__(self) -> str:
        result = hex(self.runtime_addr) + str(self.relevant_active_move_ids) + ": " + str(self.description()) + " references:" + ', '.join(str(x) for x in self.references)
        return result

    def __repr__(self) -> str:
        return self.__str__()
