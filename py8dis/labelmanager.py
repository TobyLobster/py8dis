"""
Label manager.

A label names a runtime address. This module holds the session's labels
(Labels: a Label object for each address that has one, see label.py), and
a few functions that work on all of them: addr() finds a name's address,
assign_local_label_output_names() makes sure local label names don't
clash, and all_labels_as_comments() lists them all (for debugging). The
names themselves are chosen in disassembly.py.

We discover the need for labels during the tracing process, but wait
until tracing is complete before we generate the label names, just
before we emit the disassembly itself.

This gives the label naming code the maximum amount of information we
can in order to suggest useful label names.

So during tracing, the code that needs a label (see
disassembly.get_label()) says 'I want a label at runtime address A, used
(or defined) at binary address B', and perhaps 'the definition belongs to
move ID C'. It gets a LabelRef, whose name is chosen the first time it's
output (see disassembly.fix_label_names()).

A suggested name is generated automatically (or a name the label already
has is used, e.g. from label()), and the CPU and the user supplied label
maker hook function are called to actually name the label (see
disassembly.label_maker()).

Labels are used in two ways. Firstly they have a definition. They are
defined either in the disassembly itself at the start of a line, or if
they are external labels not within the range of the binary (e.g. a
call to the OS, or a zero page variable) then they are listed at the
top of the output as a 'label = value' line, in the "Memory locations"
list. (So are local labels, and labels that can't be defined inline; see
label.py.) Secondly labels are used when referenced e.g. as an operand
of an instruction.

A `Label` object stores a runtime address and multiple names each with
an associated move ID. `Simple` aka `Explicit` names are the regular
label names used to define and reference a runtime address. They are
either given (e.g. by label()) or auto-generated by py8dis (e.g.
'l1234'). `Expressions` have labels and constants with arithmetic
calculations that are understood by the assembler. Expressions are only
used when referencing an address, they are not used to define a label.

`Local Labels` are Labels that are only used within a range or ranges of
addresses. They override regular labels.

So what do move IDs do for us? (A move ID identifies a move, a block of
the binary that the program copies to another runtime address before
running it; see movemanager.py. Move ID 0, the base move, is for
everything that runs where it's loaded.)

Firstly, they help us emit label definitions in the "right" places. If
we have two separate fragments of code which are each move()d to runtime
address &900 and both contain a branch to address &903, we'd like each
of those fragments to have a separate inline label definition at
address &903, so one fragment isn't "missing" a label to show control
transfers in at &903 sometimes.

So move IDs provide optional "annotations" on individual label names.
They are "advisory" - labels just resolve to 16-bit integer addresses,
of course - but they should allow us to try to emit different label
names for the same address in different parts of the disassembly (i.e.
the associated pseudopc block). They also help to provide
disambiguation when tracing - where a destination address is mapped to
more than one source address, we can use heuristics like "prefer the
mapping for the move region we are currently tracing in", and maybe
also allow users to annotate to say "the target address is in move
region X".

Secondly, when we use a label to refer to a 16-bit address, we'd like
to use a "good" name. In the move() example from the previous point,
we'd like each move()d fragment to use the same name when referencing
&903 as when it emitted the label definition for that fragment.

(In some sense move IDs are entirely advisory; we could emit every
single name at the top of the disassembly as explicit definitions of
the form "foo = $1234" and the output would reassemble just fine. But
this would not be very readable or useful output.)
"""

import collections

import config
import disassembly
import movemanager
import session
import memorymanager
import utils
from memorymanager import BinaryAddr, RuntimeAddr
import label as label_module       # (not 'from label import Label', since label imports this module, indirectly)

class Labels:
    """The labels of one session (see session.py)."""

    def __init__(self):
        # A runtime address is the key of this dictionary whose value is
        # a single Label (which can hold multiple label names and expressions
        # as required).
        # (Looking up an address that has no Label yet makes one, with no
        # names, so 'labels[addr]' also means 'make sure there's a label
        # here'. Use 'addr in labels' or labels.get() just to look.)
        self.labels = utils.keydefaultdict(label_module.Label)

        # For each runtime address, the set of move_ids that are output at
        # that address. See disassembly.emit().
        self.emit_opportunities = collections.defaultdict(set)

        # The name chosen for each label reference (see disassembly.LabelRef),
        # keyed by LabelRef.key()
        self.final_names = {}

        # The names given to labels (not autogenerated), and the addresses
        # they're at, recorded when names are first chosen for optional labels
        # (see disassembly.optional_name_is_taken())
        self.names_given = None

def notify_emit_opportunity(runtime_addr, move_id):
    """Record that the move_id is output at the runtime address.

    i.e. that the main disassembly has a place, in that move, where names
    for the address can be defined inline. disassembly.emit() records these
    before it outputs anything, so that a label's names for a move that's
    never output at its address can be defined somewhere else instead (see
    Label.gather_inline_label_definitions())."""

    emit_opportunities = session.current().labels.emit_opportunities
    assert movemanager.is_valid_move_id(move_id)
    emit_opportunities[runtime_addr].add(move_id)

def addr(label_name):
    """The runtime address of the label with the given name (an explicit
    name, or a local label's name as given), or None if there isn't one. If
    several addresses have the name, the lowest is given.

    Only the names already added to labels count: e.g. an optional label's
    name doesn't until it's used, after tracing. (Used by the addr()
    command.)"""
    labels = session.current().labels.labels
    for addr, label in sorted(labels.items()):
        # Check explicit label names
        for name_list in label.explicit_names.values():
            for name in name_list:
                if label_name == name.text:
                    return addr

        # Check for local labels
        for local_labels in label.local_labels.values():
            # for each local label in the list
            for local_label in local_labels:
                if label_name == local_label.name:
                    return addr
    return None

def assign_local_label_output_names():
    """Make sure each local label name is only defined for one address.

    Local labels are defined in the output with explicit 'name = value'
    lines, so a name can only have one value. If a local label's name is
    already used for a different address (by a label() name or an earlier
    local label) then it is given a numbered name instead, e.g. 'temp_2'.
    (Names are compared in lower case, since some assemblers, e.g. 64tass,
    take 'temp' and 'TEMP' to be the same name.)

    This is called after tracing, before label names are finalised.
    (By go(), just before the first disassembly.fix_label_names().) It sets
    each LocalLabelName's output_name, and warns about each one renamed."""

    # Names already in use, and the address they are used for
    labels = session.current().labels.labels
    taken = {}
    for runtime_addr, label in labels.items():
        for name_list in label.explicit_names.values():
            for name in name_list:
                taken.setdefault(name.text.lower(), runtime_addr)

    # Then each local label in address order: the same name can be used for
    # the same address more than once (e.g. for several ranges), but for a
    # different address it gets the first free suffix, '_2', '_3', ...
    for runtime_addr, label in sorted(labels.items()):
        for move_id in sorted(label.local_labels):
            for local_label in label.local_labels[move_id]:
                output_name = local_label.name
                suffix = 2
                while taken.get(output_name.lower(), runtime_addr) != runtime_addr:
                    output_name = "{0}_{1}".format(local_label.name, suffix)
                    suffix += 1
                if output_name != local_label.name:
                    utils.warn("local label '{0}' for {1} is output as '{2}', since '{0}' is already used for {3}".format(
                        local_label.name, config.get_assembler().hex(runtime_addr), output_name, config.get_assembler().hex(taken[local_label.name.lower()])))
                local_label.output_name = output_name
                taken[output_name.lower()] = runtime_addr

# For debugging...
def all_labels_as_comments():
    """Return all labels as comments.

    This is just intended as a debugging tool; mainly for debugging
    py8dis itself, though it might also be helpful for debugging user
    label hooks or similar.

    The explicit names of each label, by address and move ID, as lines of
    comments, output near the top with config.set_show_all_labels(True)."""

    labels = session.current().labels.labels
    formatter = config.get_assembler()
    c = formatter.comment_prefix()
    result = ["%s All labels by address and move ID" % c, "%s" % c]
    for addr, label in sorted(labels.items()):
        result.append("%s %s:" % (c, utils.plainhex4(addr)))
        for move_id, name_list in sorted(label.explicit_names.items()):
            assert movemanager.is_valid_move_id(move_id)
            result.append("%s     %4s: %s" % (c, move_id, ", ".join(sorted(x.text for x in name_list))))
    return result
