"""
Configuration

The settings belong to the current session (see session.py). Control files
change them with the functions below, e.g. config.set_hex_dump(False).
"""

import session

class Settings:
    """The settings for one session, with their initial values."""

    def __init__(self):
        self.lower_case                            = True
        self.hex_dump                              = True
        self.label_references                      = True
        self.inline_comment_column                 = 70
        self.word_wrap_comment_column              = 87
        self.indent_string                         = " "*4
        self.indent_loops                          = False
        self.blank_line_at_block_end               = True
        self.loop_limit                            = 32
        self.show_cpu_state                        = False
        self.show_autogenerated_labels             = True
        self.show_char_literals                    = True
        self.show_all_labels                       = False
        self.hex_dump_max_bytes                    = 3
        self.hex_dump_show_ascii                   = True
        self.constants_are_decimal                 = True
        self.show_cycles                           = False
        self.subroutine_header                     = "*"*87
        self.subroutine_footer                     = "*"*87
        self.include_assertions                    = True
        self.label_return_instructions_numerically = True
        self.show_stats                            = True
        self.memory_region_headings                = True
        self.text_encoding                         = "ascii"    # see textencoding.py
        self.redundant_instruction_comments        = True

        # For internal use only
        self.cmos                                  = False      # True if the CPU is a 65C02

# Each setting has a getter and a setter, which use the current session's
# settings.

