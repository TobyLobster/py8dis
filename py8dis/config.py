"""
Configuration

The settings that change how the disassembly is laid out and what's in it,
which docs/configuration.md describes for users. They belong to the current
session (see session.py), which holds them in a Settings object, so reset()
puts them all back to their defaults. Control files change them with the
set_...() functions below, e.g. config.set_hex_dump(False), and the rest of
py8dis reads them with the get_...() functions, which always read the current
session's settings.

The settings, in the groups docs/configuration.md uses:

- Layout: the case of the output (lower_case); the indent (indent_string),
  and indenting the code in loops (indent_loops, with loop_limit saying what
  counts as a loop); the columns where comments go (inline_comment_column,
  word_wrap_comment_column); a blank line after each block of code
  (blank_line_at_block_end); the dividing lines of a subroutine's header
  comment (subroutine_header, subroutine_footer); and the headings in the
  "Memory locations" list at the top (memory_region_headings).

- What's shown: the hex dump at the end of each line (hex_dump,
  hex_dump_max_bytes, hex_dump_show_ascii); the comments py8dis adds, saying
  where each label is used from (label_references), what character an
  immediate value is (show_char_literals), how many cycles an instruction
  takes (show_cycles), what's known about the registers (show_cpu_state) and
  which instructions look redundant (redundant_instruction_comments); the
  lists and statistics at the end (show_autogenerated_labels, show_all_labels,
  show_stats); and the assertions that check expressions
  (include_assertions).

- Names and values: naming labels on return instructions return_1, return_2
  etc. (label_return_instructions_numerically); writing constants in decimal
  or hex (constants_are_decimal); the case of the OS calls' names
  (upper_case_os_calls); and the text encoding (text_encoding).

The last few functions are for py8dis's own use, not for control files: the
assembler object (which the session holds itself), and 'cmos', which load()
sets for the 65C02.
"""

import session

class Settings:
    """The settings for one session, with their initial values (the
    defaults). Each attribute is one setting, with the same name as its
    get_...() and set_...() functions below (e.g. 'hex_dump' for
    set_hex_dump()), which say what it does."""

    def __init__(self):
        self.lower_case                            = True
        self.hex_dump                              = True
        self.label_references                      = True
        self.inline_comment_column                 = 70
        self.word_wrap_comment_column              = 87
        self.indent_string                         = " "*4
        self.indent_loops                          = False
        self.blank_line_at_block_end               = True
        self.loop_limit                            = 32
        self.show_cpu_state                        = False
        self.show_autogenerated_labels             = True
        self.show_char_literals                    = True
        self.show_all_labels                       = False
        self.hex_dump_max_bytes                    = 3
        self.hex_dump_show_ascii                   = True
        self.constants_are_decimal                 = True
        self.show_cycles                           = False
        self.subroutine_header                     = "*"*87
        self.subroutine_footer                     = "*"*87
        self.include_assertions                    = True
        self.label_return_instructions_numerically = True
        self.show_stats                            = True
        self.memory_region_headings                = True
        self.text_encoding                         = "ascii"    # see textencoding.py
        self.redundant_instruction_comments        = True
        self.upper_case_os_calls                   = True

        # For internal use only
        self.cmos                                  = False      # True if the CPU is a 65C02

# Each setting has a getter and a setter, which use the current session's
# settings. (The setters don't check their values, except where noted.)

def get_lower_case():
    """True for lower case output, False for upper case."""
    return session.current().settings.lower_case

def set_lower_case(b):
    """Lower case output if b is True (the default), upper case if False:
    mnemonics, directives, hex digits and py8dis's own labels (see
    utils.force_case()). The command line's --lower and --upper set it too."""
    session.current().settings.lower_case = b

def get_hex_dump():
    """Whether each line ends with a comment showing its address and bytes."""
    return session.current().settings.hex_dump

def set_hex_dump(b):
    """Show each line's address and bytes in a comment at the end of the line,
    e.g. '; 2000: a2 00 ..' (True, the default), or not. The cycle counts
    and CPU state, if shown, are part of this comment, so they go too."""
    session.current().settings.hex_dump = b

def get_label_references():
    """Whether to say where each label is used from."""
    return session.current().settings.label_references

def set_label_references(b):
    """Say where each label is used from (True, the default), or not: in a
    comment before the label, e.g. '; $2002 referenced 1 time by $200b' (see
    Cpu.add_references_comments()), and in the list of labels by how often
    they're used at the end of the output."""
    session.current().settings.label_references = b

def get_inline_comment_column():
    """The column where comments at the end of a line start."""
    return session.current().settings.inline_comment_column

def set_inline_comment_column(n):
    """The column where comments at the end of a line start (70 by
    default)."""
    session.current().settings.inline_comment_column = n

def get_word_wrap_comment_column():
    """The column where comments are word wrapped."""
    return session.current().settings.word_wrap_comment_column

def set_word_wrap_comment_column(n):
    """The column where comments on lines of their own are word wrapped (87
    by default)."""
    session.current().settings.word_wrap_comment_column = n

def get_indent_string():
    """The text for one level of indent."""
    return session.current().settings.indent_string

def set_indent_string(s):
    """The text for one level of indent (four spaces by default), for
    instructions, data and indented comments."""
    session.current().settings.indent_string = s

def get_indent_loops():
    """Whether the code inside loops is indented."""
    return session.current().settings.indent_loops

def set_indent_loops(b):
    """Indent the code inside loops (see set_loop_limit()) by a level (True),
    or not (False, the default)."""
    session.current().settings.indent_loops = b

def get_blank_line_at_block_end():
    """Whether there's a blank line after each block of code."""
    return session.current().settings.blank_line_at_block_end

def set_blank_line_at_block_end(b):
    """Put a blank line after the end of each block of code, i.e. after an
    instruction that doesn't carry on to the next one, such as a jump or a
    return (True, the default), or not."""
    session.current().settings.blank_line_at_block_end = b

def get_loop_limit():
    """The most bytes a branch back to a label can be from it, for the label
    to be named as a loop."""
    return session.current().settings.loop_limit

def set_loop_limit(i):
    """The most bytes (32 by default) a branch back to a label can be from
    it, for py8dis to name the label as a loop, e.g. 'loop_c2002' (see
    disassembly.suggest_label_name())."""
    session.current().settings.loop_limit = i

def get_show_cpu_state():
    """Whether to show what's known about the registers after each
    instruction."""
    return session.current().settings.show_cpu_state

def set_show_cpu_state(b):
    """Show what's known about the registers and flags after each instruction
    (True), or not (False, the default); see docs/cpus.md. It's shown in the
    hex dump comment (see mainformatter.py), so only with
    set_hex_dump(True)."""
    session.current().settings.show_cpu_state = b

def get_show_autogenerated_labels():
    """Whether to list the labels py8dis named itself, at the end."""
    return session.current().settings.show_autogenerated_labels

def set_show_autogenerated_labels(b):
    """List, at the end of the output, the labels py8dis named itself (e.g.
    'l1234'), as a to-do list of names to give (True, the default), or not."""
    session.current().settings.show_autogenerated_labels = b

def get_show_char_literals():
    """Whether to comment immediate values that are printable characters."""
    return session.current().settings.show_char_literals

def set_show_char_literals(b):
    """Comment an immediate value that's a printable character with the
    character, e.g. "lda #$41 ; 'A'" (True, the default), or not. Only the
    6502 (where the character is in the session's text encoding, see
    set_text_encoding()) and the 8080 (where it's ASCII) add these comments;
    the Z80 doesn't."""
    session.current().settings.show_char_literals = b

def get_show_all_labels():
    """Whether to list all the labels at the top."""
    return session.current().settings.show_all_labels

def set_show_all_labels(b):
    """List all the labels, their addresses and move IDs, near the top of the
    output (True), or not (False, the default). This is for debugging
    py8dis."""
    session.current().settings.show_all_labels = b

def get_hex_dump_max_bytes():
    """The most bytes shown on a line of the hex dump."""
    return session.current().settings.hex_dump_max_bytes

def set_hex_dump_max_bytes(i):
    """The most bytes shown on a line of the hex dump (3 by default); a line
    with more shows the first few and '...'."""
    session.current().settings.hex_dump_max_bytes = i

def get_hex_dump_show_ascii():
    """Whether the hex dump shows the bytes as characters too."""
    return session.current().settings.hex_dump_show_ascii

def set_hex_dump_show_ascii(i):
    """Show the bytes as characters too at the end of the hex dump (True,
    the default), or not. (In the session's text encoding, despite the
    name: see set_text_encoding().)"""
    session.current().settings.hex_dump_show_ascii = i

def get_constants_are_decimal():
    """Whether constants are written in decimal by default."""
    return session.current().settings.constants_are_decimal

def set_constants_are_decimal(b):
    """Write constants (see commands.constant()) whose format is
    Format.DEFAULT in decimal (True, the default) or in hex (False)."""
    session.current().settings.constants_are_decimal = b

def get_show_cycles():
    """Whether to show how many cycles each instruction takes."""
    return session.current().settings.show_cycles

def set_show_cycles(b):
    """Show how many cycles each instruction takes, e.g. '7/12' for a
    conditional jump (not taken/taken) (True), or not (False, the default).
    It's shown in the hex dump comment, so only with set_hex_dump(True)."""
    session.current().settings.show_cycles = b

def get_subroutine_header():
    """The dividing line at the start of a subroutine's header comment, or
    None."""
    return session.current().settings.subroutine_header

def set_subroutine_header(s):
    """The dividing line at the start of a subroutine's header comment (87
    '*'s by default), see commands.subroutine(). None leaves it out."""
    session.current().settings.subroutine_header = s

def get_subroutine_footer():
    """The dividing line at the end of a subroutine's header comment, or
    None."""
    return session.current().settings.subroutine_footer

def set_subroutine_footer(s):
    """The dividing line at the end of a subroutine's header comment (87 '*'s
    by default). None leaves it out."""
    session.current().settings.subroutine_footer = s

def get_include_assertions():
    """Whether the output ends with assertions that check expressions."""
    return session.current().settings.include_assertions

def set_include_assertions(b):
    """End the output with assertions that make the assembler check that each
    expression given with expr() has the right value (True, the default), or
    leave them out. (py8dis checks the ones it can work out the value of
    itself either way, see classification.get_expression().)"""
    session.current().settings.include_assertions = b

def get_label_return_instructions_numerically():
    """Whether labels on return instructions are named return_1, return_2
    etc."""
    return session.current().settings.label_return_instructions_numerically

def set_label_return_instructions_numerically(b):
    """Name an auto-generated label on a return instruction return_1,
    return_2 and so on (True, the default), or like any other label (see
    each CPU's label_maker())."""
    session.current().settings.label_return_instructions_numerically = b

def get_show_stats():
    """Whether the output ends with statistics."""
    return session.current().settings.show_stats

def set_show_stats(b):
    """End the output with statistics: how much of it is code, data and
    strings (True, the default), or not. See stats.py."""
    session.current().settings.show_stats = b

def get_memory_region_headings():
    """Whether the "Memory locations" list is grouped by region, under
    headings."""
    return session.current().settings.memory_region_headings

def set_memory_region_headings(b):
    """Group the "Memory locations" list at the top of the output by memory
    region, under headings (see memory_region()), or not."""
    session.current().settings.memory_region_headings = b

def get_redundant_instruction_comments():
    """Whether to comment instructions whose results are never used."""
    return session.current().settings.redundant_instruction_comments

def set_redundant_instruction_comments(b):
    """Comment 6502 and Z80 instructions whose results are never used, ';
    Redundant instruction?' (see Cpu6502.find_redundant_instructions() and
    CpuZ80.find_redundant_instructions())."""
    session.current().settings.redundant_instruction_comments = b

def get_upper_case_os_calls():
    """Whether the OS calls are named in capitals."""
    return session.current().settings.upper_case_os_calls

def set_upper_case_os_calls(b):
    """Name the OS's calls in capitals, as the manufacturer's documentation
    does: the Acorn MOS's (e.g. OSBYTE, OSWRCH, GSINIT) and the Commodore
    Kernal's (e.g. CHROUT, SETLFS), and Commodore's other names, from its
    source (see commodore.location_names()), and CP/M's BDOS and its
    functions (e.g. C_WRITESTR); or in lower case (e.g. osbyte, chrout).
    py8dis's descriptive names (e.g. 'tape_buffer') are in lower case either
    way. Call it before acorn.bbc(), commodore.c64() etc., which name them:
    calling it afterwards stops with an error (utils.die()), since the names
    have already been given."""
    if session.current().extras.get("os_calls_named"):
        import utils
        utils.die("config.set_upper_case_os_calls(): call it before acorn.bbc(), commodore.c64() etc., which name the OS calls")
    session.current().settings.upper_case_os_calls = b

def get_text_encoding():
    """The name of the session's text encoding, e.g. "ascii" (see
    textencoding.current() for the encoding itself)."""
    return session.current().settings.text_encoding

def set_text_encoding(name):
    """How bytes in strings (and the hex dump, and character comments) are
    shown as text: "ascii" (the default), "petscii" or "screen" (Commodore
    screen codes). See textencoding.py. Stops with an error (utils.die()) for
    an unknown name."""
    import textencoding
    textencoding.get(name)
    session.current().settings.text_encoding = name


# For internal use only:

def get_assembler():
    """The assembler object used to emit the disassembly (e.g. an Acme object)."""
    return session.current().assembler

def set_assembler(f):
    """Replace the session's assembler object with 'f' (see
    session.make_assembler())."""
    session.current().assembler = f

def get_cmos():
    """True if the CPU is a 65C02, so the assembler must accept its extra
    instructions."""
    return session.current().settings.cmos

def set_cmos(b):
    """Say whether the CPU is a 65C02. load() sets this, and the assemblers
    that need telling about the 65C02's instructions (e.g. beebasm's 'CPU 1')
    read it."""
    session.current().settings.cmos = b
