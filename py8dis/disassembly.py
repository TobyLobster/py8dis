class DisassemblyState:
    """The state of this module for one session (see session.py)."""

    def __init__(self):
        # A user supplied function that creates a label name based on context
        self.user_label_maker_hook = None

        # The set of labels that have not been explicitly set by the user, but
        # just given a default label name by py8dis.
        self.autogenerated_labels = set()

        # `format_hint` stores formatter functions indexed by binary address.
        self.format_hint = {}

        # Optional labels are only output if they are used.
        #
        # `optional_labels` stores an object of class OptionalLabel indexed by
        # runtime address, as created by `optional_label()`
        self.optional_labels = {}

        # Optional labels for the code in a range of binary addresses (see
        # add_range_optional_labels()): a list of RangeOptionalLabels
        self.range_optional_labels = []

        # The memory mapped I/O: (start, end) runtime addresses, 'end'
        # exclusive (see commands.io_range()). Reading it can have side
        # effects.
        self.io_ranges = []

        # `constants` is a list of class Constant.
        self.constants = []

        # What emit() output for each classification, for the JSON output
        # (see jsonoutput.py): (binary location, classification, the line
        # objects for the classification itself), in output order
        self.output_items = []

        # Where emit() output labels (and perhaps comments) at the start or
        # end of a range of the output, rather than for an item: (binary
        # location, whether comments were output), for the JSON
        self.output_range_boundaries = []

        # The heading each label's "Memory locations" definitions are under,
        # by runtime address (if there are headings), for the JSON output
        self.memory_location_headings = {}

        # Named regions of memory (see add_memory_region()), as (start, end,
        # name) with 'end' exclusive, used to group the "Memory locations"
        # list at the top of the output
        self.memory_regions = []

        # Annotations are comments or other raw strings output to the
        # assembly.
        #
        # An address can have an arbitrary number of annotations; we may need
        # to slide them around in the code slightly to fit them round
        # multi-byte classifications. By using a list we preserve the relative
        # order of additions. We do sort this based on the annotation
        # priorities but this is a stable sort and preserves order for any
        # particular annotation type.
        self.annotations = collections.defaultdict(list)

def set_user_label_maker_hook(hook):
    """Set the user supplied 'hook' function that makes label names.

    (See _label_maker() for how it's called. It can only be set once:
    commands.set_label_maker_hook() checks.)"""

    state = session.current().disassembly
    assert state.user_label_maker_hook is None
    state.user_label_maker_hook = hook

def comment(runtime_addr, text, *, word_wrap=True, indent=0, align=Align.BEFORE_LABEL, auto_generated=False):
    """Add a comment.

    Define a comment string to appear in the assembly code at the
    given address in the output. The comment can be inlined (added
    to the end of the line), or standalone (a separate line of output).
    The comment can be automatically word wrapped.

    The runtime address must have one binary location (see
    movemanager.r2b_checked()), where data is loaded. 'align' says where
    the comment goes (see Align), and 'indent' is its indent level.
    'auto_generated' is True for a comment py8dis makes rather than one the
    control file asks for (see comment_binary()).
    """

    binary_loc = movemanager.r2b_checked(runtime_addr)
    assert memorymanager.is_data_loaded_at_binary_addr(binary_loc.binary_addr)

    comment_binary(binary_loc, text, word_wrap=word_wrap, indent=indent, align=align, auto_generated=auto_generated)

def comment_binary(binary_loc, text, *, word_wrap=False, indent=0, align=Align.BEFORE_LABEL, auto_generated=True, priority=None):
    """Add a comment, either inline or standalone.

    As comment(), but at a binary location: a BinaryLocation, or a binary
    address (taken to be in the innermost active move, or if none is, the
    move it's in: see movemanager.make_binloc()). An auto_generated comment
    isn't added at an address marked with no_automatic_comment().
    'priority' orders it among the annotations with the same 'align' at the
    same place (lowest first)."""

    annotations = session.current().disassembly.annotations
    binary_loc = movemanager.make_binloc(binary_loc)
    if auto_generated and (binary_loc.binary_addr in session.current().trace.no_auto_comment_set):
        return

    new_comment = Comment(text, word_wrap, indent, align=align, priority=priority, auto_generated=auto_generated)

    annotations[binary_loc].append(new_comment)

def add_raw_annotation(binary_loc, text, *, align=Align.BEFORE_LABEL, priority=None):
    """Add a raw string to the output.

    (Output as it is, e.g. "" for a blank line, at the binary location: see
    add_annotation().)"""

    add_annotation(binary_loc, Annotation(text, align, priority))

def add_annotation(binary_loc, annotation):
    """Add an annotation (see comment.py) to the output.

    It's output at the binary location (a BinaryLocation, or a binary
    address, see movemanager.make_binloc()), where its 'align' says: before
    or after the label, before or after the line, or inline. (One at an
    address inside a multi-byte instruction or data item that isn't inline
    is output after the item, see emit_addr().)"""

    annotations = session.current().disassembly.annotations
    binary_loc = movemanager.make_binloc(binary_loc)
    annotations[binary_loc].append(annotation)

def annotate_binary(binary_loc, s, *, align=Align.BEFORE_LABEL, priority=None, once_only=False):
    """Add a raw string directly to the assembly code output at the
    given address.

    (The binary location, see add_raw_annotation().) With 'once_only', it
    isn't added if the same raw string is already there, e.g. for a blank
    line that several snippets might ask for."""

    # Check if it's already been added
    annotations = session.current().disassembly.annotations
    if once_only:
        # (Only raw annotations are compared, not comments)
        match = next((True for a in annotations[binary_loc] if type(a) is Annotation and a.text == s), None)
        if match is not None:
            return
    add_raw_annotation(binary_loc, s, align=align, priority=priority)

def add_constant(value, name, comment=None, align=Align.INLINE, format=Format.DEFAULT):
    """Create a named constant value.

    It's defined as 'name = value' near the top of the output (see
    emit_constants()), with its comment placed by 'align', and its value
    written in 'format' (see constant_value_to_string()). It's only used
    where an expression uses its name (e.g. from expr())."""

    # Make sure we don't add the same constant twice. Stop with an error if
    # trying to redefine a constant with a different value.
    constants = session.current().disassembly.constants
    for c in constants:
        if c.name == name:
            if c.value != value:
                utils.die("constant({0}, {1!r}): '{1}' is already defined as {2}".format(value, name, c.value))
            return

    constants.append(constant.Constant(value, name, comment, align, format))

def define_forward_zero_page_labels_first():
    """Define at the top of the output (rather than inline) each zero page
    label that a zero page instruction uses before the label would be
    defined inline, e.g. 'lda $80' before code moved to &80. (An assembler
    has to choose an instruction's size when it first sees it, and for a
    label it doesn't know yet it chooses an absolute address, so the
    instruction would be a byte longer: acme and xa warn, and beebasm
    stops.) Called once the code has been traced.

    (By go(), at the start of stage 3 in the module docstring, before any
    label names are chosen. It sets each such label's definable_inline to
    False. A CPU without zero page instructions, i.e. without an OpcodeZp
    class, has nothing to do.)"""

    cpu = session.current().cpu
    zp_opcode = getattr(cpu, "OpcodeZp", None)
    if zp_opcode is None:
        return
    memory_binary = session.current().memory.binary
    classifications = session.current().classifications.classifications
    expressions = session.current().classifications.expressions
    moves = session.current().moves
    for runtime_addr, label in session.current().labels.labels.items():
        if runtime_addr >= 0x100 or not label.definable_inline:
            continue

        # Where it would be defined inline: before the classification its
        # address is in (in any move whose data covers it). (A label inside
        # a classification is defined just before it, relative to its
        # start, so step back to the start.)
        definition_addrs = []
        for move_id in range(len(moves.move_definitions)):
            binary_addr, _ = movemanager.r2b(runtime_addr, move_id)
            if binary_addr is None or binary_addr >= 0x10000 or memory_binary[binary_addr] is None:
                continue
            while binary_addr > 0 and classifications[binary_addr] is classification.INSIDE_A_CLASSIFICATION:
                binary_addr -= 1
            definition_addrs.append(binary_addr)
        if not definition_addrs:
            continue

        # (An instruction whose operand has an expression is left alone: the
        # control file has chosen what it is, e.g. dfs226's
        # 'sta tube_brkv_handler_fwd,x', where that's a constant)
        last_definition_addr = max(definition_addrs)
        for reference in label.references:
            if (reference.binary_addr < last_definition_addr
                    and isinstance(classification.get_classification(reference.binary_addr), zp_opcode)
                    and reference.binary_addr + 1 not in expressions):
                label.definable_inline = False
                break

def is_simple_name(s):
    """Check the name is a simple valid label name.

    Must be a single letter or underscore followed by any number of
    alphanumerics or underscores

    (Anything else, e.g. 'table+1', is taken to be an expression.) 's' must
    be a non-empty string, or an expression tree, which is never a simple
    name."""

    # (An expression made by e.g. make_add() is never a simple name)
    if isinstance(s, expression.Expr):
        return False
    assert utils.is_string_type(s)
    assert len(s) > 0

    def valid_first(c):
        return c.isalpha() or c == "_"
    def valid_later(c):
        return c.isalnum() or c == "_"
    return valid_first(s[0]) and all(valid_later(c) for c in s)

def add_label(runtime_addr, s, move_id, *, is_autogenerated=False, definable_inline=True, priority=None):
    """Add a label at the given runtime address and move_id.

    A simple name 's' is added as an explicit name (with 'priority', see
    Label.ExplicitName), and anything else as an expression (if
    'is_autogenerated', only if the label doesn't have it already). With
    's' None the label is just made, if it doesn't exist (e.g. for an entry
    point, so that it's named later). definable_inline=False makes all the
    label's names be defined in the "Memory locations" list (it can't be
    turned back on). Returns the Label."""

    memorymanager.is_valid_runtime_addr(runtime_addr, True) # 0x10000 is valid for labels

    label = session.current().labels.labels[runtime_addr]
    label.definable_inline = label.definable_inline and definable_inline
    if s is not None:
        if is_simple_name(s):
            label.add_explicit_name(s, move_id, is_autogenerated=is_autogenerated, priority=priority)
        else:
            label.add_expression(s, move_id, force=not is_autogenerated)

    # Make sure the move_id specified is added in the list of relevant and active move ids,
    # since it can be used to annotate the reference
    if move_id and move_id not in label.relevant_active_move_ids:
        label.relevant_active_move_ids.append(move_id)

    return label

def add_optional_label(runtime_addr, s, *, base_addr=None, definable_inline=True):
    """Add a label at the given runtime address, but only output if used.

    When two consecutive bytes share a base label name (e.g. `userv`
    and `userv+1`) then `base_addr` points to the first byte.

    The name is only added to the address's label when something refers to
    the address (see suggest_label_name()), and only if no other address
    has been given the name (see optional_name_is_taken()). Without a base
    address it must be a simple name; with one it's an expression, e.g.
    'userv+1', and the base address must already have an optional label of
    its own (with no base address). Adding the same optional label again
    does nothing; a different one at the same address stops with
    utils.die(), as does any other problem. definable_inline=False makes
    the name always be defined in the "Memory locations" list (e.g. for
    hardware registers)."""

    optional_labels = session.current().disassembly.optional_labels
    h = config.get_assembler().hex
    def check(ok, problem):
        if not ok:
            base_str = "" if base_addr is None else ", " + h(base_addr)
            utils.die("optional_label({0}, {1!r}{2}): {3}".format(h(runtime_addr), s, base_str, problem))

    assert 0 <= runtime_addr <= 0xffff

    new_label = optionallabel.OptionalLabel(s, base_addr, definable_inline)

    # Check if already present
    if runtime_addr in optional_labels:
        old_label = optional_labels[runtime_addr]
        check(old_label == new_label, "there is already a different optional label '{0}' here".format(old_label.name))
        return

    # Check base_addr is valid
    if base_addr is not None:
        assert 0 <= base_addr <= 0xffff
        check(runtime_addr != base_addr, "the base address must be a different address")
        check(base_addr in optional_labels, "the base address needs an optional label defined first")
        check(optional_labels[base_addr].base_address is None, "the base address's optional label must not itself have a base address")
    else:
        check(is_simple_name(s), "this isn't a valid label name (a letter or underscore followed by letters, digits or underscores)")
    optional_labels[runtime_addr] = new_label

class RangeOptionalLabels:
    """Optional labels for the code and data in a range of binary addresses
    (see add_range_optional_labels())."""
    def __init__(self, start_addr, end_addr, names, heading):
        self.start_addr = start_addr
        self.end_addr = end_addr
        self.names = names          # {runtime address: (name, base runtime address or None)}
        self.heading = heading

def add_range_optional_labels(start_addr, end_addr, names, heading=None):
    """Names for the addresses used by the code and data from binary address
    start_addr to end_addr, instead of the optional labels (e.g. the names
    of another machine's memory, for code that runs on it, see
    commodore.drive1541_code()). `names` is {runtime address: (name, base
    runtime address or None)}, as for optional labels (e.g. 'buffer+1', with
    the base address of 'buffer'). A name used is defined as a local label
    for the range (under `heading` in the "Memory locations" list, if
    given). An address with no name here gets an ordinary name there, not
    an optional label's; a name the control file gives an address is kept.
    """
    session.current().disassembly.range_optional_labels.append(RangeOptionalLabels(start_addr, end_addr, names, heading))

def _range_optional_label(lmd, runtime_addr, binary_addr, binary_addr_type):
    """For a label used in a range with optional labels of its own (see
    add_range_optional_labels()): (True, lmd with its name) if it has one
    there, (True, None) if it doesn't (so the optional labels aren't used),
    or (False, None) if it isn't used in such a range, or the control file
    has named it. (An optional label's name, once it's used outside the
    range, is one of the label's explicit names too, but not one the control
    file gave, so the range's name is still used in the range.)"""
    if binary_addr_type != BinaryAddrType.BINARY_ADDR_IS_AT_LABEL_USAGE:
        return False, None
    for r in session.current().disassembly.range_optional_labels:
        if r.start_addr <= binary_addr < r.end_addr:
            break
    else:
        return False, None
    label = session.current().labels.labels[runtime_addr]
    if any(not name.is_autogenerated and not name.from_optional_label for names in label.explicit_names.values() for name in names):
        return False, None
    if runtime_addr not in r.names:
        return True, None

    def define(addr, name):
        """The name to use for the address in this range: it's added as a
        local label for the range, if it isn't already, and its output name
        is returned."""
        # (As a local label for the range, once)
        label = session.current().labels.labels[addr]
        for local_label in label.local_labels[movemanager.BASE_MOVE_ID]:
            if local_label.name == name and (local_label.start_addr, local_label.end_addr) == (r.start_addr, r.end_addr):
                return local_label.output_name
        add_local_label(RuntimeAddr(addr), name, r.start_addr, r.end_addr, heading=r.heading)
        return name

    name, base = r.names[runtime_addr]
    if base is None:
        lmd.name = define(runtime_addr, name)
    else:
        lmd.name = "%s+%d" % (define(base, r.names[base][0]), runtime_addr - base)
    lmd.defined_in_move_id = movemanager.BASE_MOVE_ID
    return True, lmd

def add_local_label(runtime_addr, name, start_addr, end_addr, move_id=None, heading=None):
    """Add a label at the given runtime address, valid only if referenced in the region specified.

    start_addr, end_addr are binary addresses: the name is used where the
    label is referred to from code or data from start_addr up to (but not
    including) end_addr (see suggest_label_name()). (Without moves, binary
    and runtime addresses are the same.) `move_id` is the move the name is
    for (the base move if None).

    `heading` is the heading to define it under in the "Memory locations"
    list, if not its memory region's (see memory_location_definitions()).
    """

    label = session.current().labels.labels[runtime_addr]
    label.add_local_label(name, start_addr, end_addr, move_id, heading)

def get_label(runtime_addr, binary_addr, *, binary_addr_type: BinaryAddrType, move_id=None):
    """Get a label name (a lazy string) for the given runtime address.

    `binary_addr` is the binary address where the label is being used, or the binary address of the label definition.
    `binary_addr_type` says which type of binary_addr we have: a usage or the definition.
    `move_id` is the move, for the definition.

    This is how code that writes an address (e.g. an instruction's operand)
    gets the label for it. It returns a LabelRef, whose name isn't chosen
    until it's first turned into text, once tracing is done."""

    runtime_addr = RuntimeAddr(runtime_addr)
    binary_addr = BinaryAddr(binary_addr)

    assert memorymanager.is_valid_runtime_addr(runtime_addr, True) # 0x10000 is valid for labels
    assert memorymanager.is_valid_binary_addr(binary_addr)
    assert move_id is None or movemanager.is_valid_move_id(move_id)

    # We ensure the labelmanager knows there's a label at this address so it can
    # emit a definition. It's tempting to try to defer this until
    # get_final_label() is called, but it's good to have the label exist as
    # early as possible - for example, this means post-tracing code analysis can
    # see where labels exist and what references them.

    # Ensure the label exists (with the appropriate active/relevant move ids)
    session.current().labels.labels[runtime_addr]

    return LabelRef(runtime_addr, binary_addr, move_id, binary_addr_type)

class LabelRef(utils.LazyString):
    """A reference to a label, from get_label(): the label's runtime address,
    and where it's used or defined (see get_label()). Its name is chosen (see
    get_final_label()) the first time this reference, or an equal one, is
    converted to a string (see name_labels()), and kept in the session.

    (Whatever name is chosen, its value is the runtime address. This is used
    when evaluating expressions, see expression.py.)"""

    def __init__(self, runtime_addr, binary_addr, move_id, binary_addr_type):
        # (As a LazyString, its text is just itself: see __str__())
        super().__init__("%s", self)
        self.runtime_addr = runtime_addr
        self.binary_addr = binary_addr
        self.move_id = move_id
        self.binary_addr_type = binary_addr_type

    def key(self):
        """What identifies the reference: two references with the same key
        are given the same name."""
        return (int(self.runtime_addr), int(self.binary_addr), self.move_id, self.binary_addr_type)

    def __str__(self):
        if self.resolved is None:
            final_names = session.current().labels.final_names
            key = self.key()
            name = final_names.get(key)
            if name is None:
                name = get_final_label(self.runtime_addr, self.binary_addr, self.move_id, binary_addr_type=self.binary_addr_type)
                final_names[key] = name
            self.resolved = name
        return self.resolved

    def __repr__(self):
        return "LabelRef({0}, {1}, {2}, {3})".format(hex(self.runtime_addr), hex(self.binary_addr), self.move_id, self.binary_addr_type.name)

def get_emitted_label(runtime_addr):
    """Get the name of an existing, emitted label name for the given runtime address, or just
    return the address as a string.

    i.e. one of the label's explicit names that has already been defined in
    the output (see Label.get_already_emitted_name()), so no new name is
    chosen. Otherwise it's the address as a number (see
    mainformatter.uint_formatter()), or in hex for &10000. (Used for
    beebasm's COPYBLOCK and CLEAR around a moved block, see
    beebasm.pseudopc_start().)"""

    runtime_addr = RuntimeAddr(runtime_addr)

    assert memorymanager.is_valid_runtime_addr(runtime_addr, True) # 0x10000 is valid for labels

    # if the label exists, get a name that has already been emitted
    if runtime_addr in session.current().labels.labels:
        label = session.current().labels.labels[runtime_addr]
        emitted_name = label.get_already_emitted_name()
        if emitted_name:
            return emitted_name

    # No label name found, output the address as a hex literal
    if runtime_addr > 0xffff:
        # e.g. the end of a move at the very top of memory
        return config.get_assembler().hex(runtime_addr)
    return mainformatter.uint_formatter(runtime_addr, 16)

def optional_name_is_taken(runtime_addr):
    """Whether the name of the optional label at the runtime address (or of
    its base address's, for e.g. 'userv+1') was given to a label at another
    address, e.g. by the control file. Then it isn't used, since the name
    would be defined twice.

    (The names given are recorded when names are first chosen for optional
    labels, before any optional label's name is added to its label. They're
    compared in lower case, since some assemblers, e.g. 64tass, take 'key'
    and 'KEY' to be the same name.)"""
    labels = session.current().labels
    if labels.names_given is None:
        labels.names_given = collections.defaultdict(set)
        for addr, label in labels.labels.items():
            for name_list in label.explicit_names.values():
                for name in name_list:
                    if not name.is_autogenerated:
                        labels.names_given[name.text.lower()].add(addr)
    optional_labels = session.current().disassembly.optional_labels
    optional_label = optional_labels[runtime_addr]
    if optional_label.base_address is not None:
        runtime_addr = optional_label.base_address
        optional_label = optional_labels[runtime_addr]
    return bool(labels.names_given.get(optional_label.name.lower(), set()) - {runtime_addr})

def suggest_label_name(runtime_addr, binary_addr, move_id, binary_addr_type: BinaryAddrType):
    """Return a suggestion for a label name as a LabelMakingData object.

    The label is at runtime_addr, and it's used or defined at binary_addr,
    as binary_addr_type says. move_id is the move for the definition, if
    it's known (otherwise None). The suggestion is, in order of preference:

    - a name from add_range_optional_labels(), for a label used in such a
      range;
    - a name the label already has (a local label for where it's used, an
      explicit name, or an expression), for the best move (see the rules
      below);
    - the address's optional label's name, if it has one;
    - otherwise, a new name made from the address (auto-generated): e.g.
      'l1234' for data, 'c1234' for code, 'sub_c1234' for code that's only
      called as a subroutine (or an entry point no instruction refers to),
      or 'loop_c1234' for code only reached by a branch back from up to
      config.get_loop_limit() bytes later (which also indents the loop with
      config.set_indent_loops(True)).
    """

    optional_labels = session.current().disassembly.optional_labels
    assert binary_addr is not None
    runtime_addr = RuntimeAddr(runtime_addr)

    lmd = labelmakingdata.LabelMakingData("",                       # name (to be filled in below)
                                          runtime_addr, move_id,    # runtime_addr is the actual value of the label and therefore where it should be defined (in move_id).
                                          binary_addr,              # binary_addr is where the label is...
                                          binary_addr_type=binary_addr_type,         # ...defined or used
                                          is_autogenerated=False,
                                          is_expression=False)

    # A range with optional labels of its own (see add_range_optional_labels())
    in_range, range_lmd = _range_optional_label(lmd, runtime_addr, binary_addr, binary_addr_type)
    if range_lmd is not None:
        return range_lmd

    # Work out the best move_id to use for the label.
    #
    # The basic idea is that:
    # (a) if we can assign a move ID based on a matching of binary_addr and
    #     runtime_addr move IDs then do that
    # (b) else *if* there is any existing label at the address we will use
    #     it's move_id rather than forcing a new label in BASE_MOVE_ID to
    #     be created.
    #
    # The actual rules are:
    #
    # 1. If a move ID is already specified, use that. (Otherwise start
    #    with the move ID of binary_addr.)
    # 2. Choose the move ID of the binary_address if it's the same
    #    as a move ID of the runtime address.
    # 3. Look for any label at the runtime address that has a
    #    `move_id` that matches one at either the runtime address or
    #    binary address. If found, we have got our ideal label so
    #    return it (the LabelMakingData with that name and move ID).
    #    We look in order through the local labels, then the explicit
    #    labels, then the expressions.
    # 4. If there is only one valid move_id at the runtime address,
    #    select that move ID. (It makes more sense to create a label
    #    there than in the base move ID).
    # 5. All else has failed, so use the base move ID.
    #
    # (move_ids_for_runtime_addr() only gives the moves other than the base
    # move, so without any moves, rule 3 looks in the base move, and rule 5
    # chooses it.)

    # Rule 1
    if move_id is None:
        move_id = session.current().moves.move_id_for_binary_addr[binary_addr]
    move_ids2 = movemanager.move_ids_for_runtime_addr(runtime_addr)

    # Rule 2
    if move_id not in move_ids2:
        candidate_move_ids = list(move_ids2)
        if move_id is not None:
            candidate_move_ids = [move_id] + candidate_move_ids

        # Get the label
        label = session.current().labels.labels.get(runtime_addr)

        for candidate_move_id in candidate_move_ids:
            # Rule 3: Local labels
            if candidate_move_id in label.local_labels:
                for local_label in label.local_labels[candidate_move_id]:
                    if local_label.start_addr <= binary_addr < local_label.end_addr:
                        lmd.name = local_label.output_name
                        lmd.defined_in_move_id = candidate_move_id
                        return lmd

            # Rule 3: Explicit labels
            if candidate_move_id in label.explicit_names:
                for name in label.explicit_names[candidate_move_id]:
                    lmd.name = name.text
                    lmd.defined_in_move_id = candidate_move_id
                    return lmd

            # Rule 3: Expressions
            if candidate_move_id in label.expressions:
                for expression_text in label.expressions[candidate_move_id]:
                    lmd.name = expression_text
                    lmd.defined_in_move_id = candidate_move_id
                    lmd.is_expression = True
                    return lmd

        if len(move_ids2) == 1:
            # Rule 4
            move_id = min(move_ids2)
        else:
            # Rule 5
            move_id = movemanager.BASE_MOVE_ID

    label = session.current().labels.labels.get(runtime_addr)
    assert label is not None

    # If the runtime address has a label name, choose the first one.
    # Check the local labels, then explicit names then expressions in
    # our chosen move ID.
    # If that fails try the base move ID.

    # We are just returning the first name arbitrarily, since we
    # have no basis to choose anything else.

    # We look for a local label, explicit label or expression in the
    # current move_id, or failing that in the BASE_MOVE_ID.
    for local_label in label.local_labels[move_id]:
        if local_label.start_addr <= binary_addr < local_label.end_addr:
            lmd.name = local_label.output_name
            lmd.defined_in_move_id = move_id
            return lmd

    # return with the first explicit name if there is one
    for name in label.explicit_names[move_id]:
        lmd.name = name.text
        lmd.defined_in_move_id = move_id
        return lmd

    # return with the first expression name, if there is one
    for expression_text in label.expressions[move_id]:
        lmd.name = expression_text
        lmd.defined_in_move_id = move_id
        lmd.is_expression = True
        return lmd

    # Now do the same again, but with the BASE_MOVE_ID (so any name found
    # there is defined in the BASE_MOVE_ID)
    for local_label in label.local_labels[movemanager.BASE_MOVE_ID]:
        if local_label.start_addr <= binary_addr < local_label.end_addr:
            lmd.name = local_label.output_name
            lmd.defined_in_move_id = movemanager.BASE_MOVE_ID
            return lmd

    for name in label.explicit_names[movemanager.BASE_MOVE_ID]:
        lmd.name = name.text
        lmd.defined_in_move_id = movemanager.BASE_MOVE_ID
        return lmd

    for expression_text in label.expressions[movemanager.BASE_MOVE_ID]:
        lmd.name = expression_text
        lmd.defined_in_move_id = movemanager.BASE_MOVE_ID
        lmd.is_expression = True
        return lmd

    # If no explicit label or expression is suitable, try the optional
    # labels (unless its name is another address's).
    if runtime_addr in optional_labels and not in_range and not optional_name_is_taken(runtime_addr):
        existing_label = optional_labels[runtime_addr]
        if not existing_label.definable_inline:
            label.definable_inline = False
        if existing_label.base_address is not None:
            # The name is relative to its base address's (e.g.
            # 'tape_buffer+1'), so that needs a label too, if this name is
            # used (see label_maker())
            lmd.optional_base = (existing_label.base_address, existing_label.definable_inline)

        lmd.name = existing_label.name
        lmd.defined_in_move_id = None
        return lmd

    # Make up a brand new label name.
    #
    # Find where the label will be defined in the binary, in the move we have
    # chosen. (Without the move ID this would fail where several moves cover
    # the runtime address, and could find the wrong move.)
    #
    # Note that `binary_addr` (where the label is used or defined) is reused
    # below to mean where the label will be defined.
    binary_addr, _ = movemanager.r2b(runtime_addr, move_id)

    # if the binary address is not code, then call it "lXXXX"
    if binary_addr is None or not classification.is_code(binary_addr):
        label = utils.force_case("l%04x" % runtime_addr)
    else:
        # Assume label is "cXXXX", c for code, but may change to
        # "sub_cXXXX" or "loop_cXXXX"
        label = utils.force_case("c%04x" % runtime_addr)

        binary_loc_refs = session.current().trace.references.get(movemanager.BinaryLocation(binary_addr, move_id), [])

        if binary_loc_refs:
            # A subroutine if every reference is a call (e.g. JSR)
            is_subroutine = all(session.current().cpu.is_subroutine_call(ref_binary_loc.binary_addr) for ref_binary_loc in binary_loc_refs)
        else:
            # There are no references recorded. Code given as an entry point
            # (e.g. by entry(), or a jump table via code_ptr() or wordentry(),
            # whose references from data aren't recorded) is named as a
            # subroutine. Other code (e.g. a label only used to define a
            # nearby label like 'x = label+1') is not.
            is_subroutine = binary_addr in session.current().cpu.explicit_entry_points

        if is_subroutine:
            # Found a subroutine, label is "sub_XXXX"
            label = "sub_" + label
        else:
            # Look for loops
            #
            # If there is one reference, and it's a branch backwards to
            # the target address, and within loop_limit bytes of the
            # current address then it's a "loop_cXXXX" name.
            if len(binary_loc_refs) == 1:
                ref_binary_addr = list(binary_loc_refs)[0].binary_addr
                ref_runtime_addr = movemanager.b2r(ref_binary_addr)

                # (A branch back to an RTS is named 'return_N' instead, by
                # the CPU's label_maker(), unless
                # config.set_label_return_instructions_numerically(False))
                if session.current().cpu.is_branch_to(ref_binary_addr, runtime_addr):
                    if 0 <= ref_runtime_addr - runtime_addr < config.get_loop_limit():
                        label = "loop_" + label
                        if config.get_indent_loops():
                            # Indent the code from here to the branch back
                            # (an extra indent level each time, so a loop
                            # inside another is indented further)
                            while binary_addr <= ref_binary_addr:
                                c = classification.get_classification(binary_addr)
                                if c is not None:
                                    if c.is_code(binary_addr):
                                        c.indent(binary_addr)
                                    binary_addr += c.length()
                                else:
                                    binary_addr += 1
    lmd.name = label
    lmd.defined_in_move_id = move_id
    lmd.is_autogenerated = True
    return lmd

def label_maker(runtime_addr, binary_addr, move_id, binary_addr_type: BinaryAddrType):
    """Get a label name via calling a user hook (see _label_maker()).

    Returns the LabelMakingData with the name chosen. If the name chosen is
    an optional label's that's relative to another address's (e.g.
    'tape_buffer+1'), that address gets a label too (the base address's
    optional label's name, added as auto-generated)."""

    lmd = _label_maker(runtime_addr, binary_addr, move_id, binary_addr_type)
    optional_base = lmd.optional_base
    if optional_base is not None:
        optional_labels = session.current().disassembly.optional_labels
        base_address, definable_inline = optional_base
        if lmd.name == optional_labels[runtime_addr].name:
            add_label(base_address, optional_labels[base_address].name, move_id=None, is_autogenerated=True, definable_inline=definable_inline)
    return lmd

def _label_maker(runtime_addr, binary_addr, move_id, binary_addr_type: BinaryAddrType):
    """Get a label name via calling a user hook.

    `binary_addr` is the associated binary address using the `move_id`.

    Returns a LabelMakingData with the name chosen, and the move ID it's
    for. The name is chosen in three steps: suggest_label_name() suggests
    one, the CPU's label_maker() can change it (e.g. to 'return_1' for an
    RTS), then the control file's label maker hook, if there is one, can
    change the name or the move ID (and then the name doesn't count as
    auto-generated). Otherwise an auto-generated name is recorded for the
    list of auto-generated labels at the end of the output."""

    autogenerated_labels = session.current().disassembly.autogenerated_labels
    user_label_maker_hook = session.current().disassembly.user_label_maker_hook
    assert session.current().cpu.trace_done

    # Get a LabelMakingData object with a suggested label name.
    # The runtime_address and move_id represent the place where the label should be defined.
    # binary_addr is an address where either (a) the label is being used (e.g. the address of an
    # operand of an instruction like 'LDA label'), or (b) where it is being defined. This is
    # specified by binary_addr_type.
    lmd = suggest_label_name(runtime_addr, binary_addr, move_id, binary_addr_type)

    # Default CPU based helper, possibly updating the suggestion
    session.current().cpu.label_maker(lmd)

    # if the user function is supplied, use it to select the name
    # passing in the suggestion we just made.
    if user_label_maker_hook is not None:
        # remember our best automatic label making data
        original_lmd = lmd.copy()

        sig = inspect.signature(user_label_maker_hook)
        if len(sig.parameters) == 1:
            # New style hook function: it changes the LabelMakingData itself
            # (e.g. with replace(), see docs/snippets-and-hooks.md)
            user_label_maker_hook(lmd)
        else:
            # Handle *legacy* hook function. This takes the suggestion as a
            # (name, move_id) tuple, and can return a new name, a new
            # (name, move_id) tuple, or the suggestion unchanged.
            # (It's called as hook(runtime address, binary address,
            # (name, move_id)), and can also return None for no change.)
            user_suggestion = user_label_maker_hook(lmd.defined_as_runtime_addr, binary_addr, (lmd.name, lmd.defined_in_move_id))
            if user_suggestion:
                if utils.is_string_type(user_suggestion):
                    lmd.name = user_suggestion
                else:
                    lmd.name = user_suggestion[0]
                    new_move_id = user_suggestion[1]
                    if new_move_id is not None and not movemanager.is_valid_move_id(new_move_id):
                        utils.die("Label maker hook returned an invalid move id {0} for label '{1}'".format(new_move_id, lmd.name))
                    lmd.defined_in_move_id = new_move_id

        # if user changed the label to something new, then return it
        if (lmd.name != original_lmd.name) or (lmd.defined_in_move_id != original_lmd.defined_in_move_id):
            lmd.is_autogenerated = False
            return lmd

    # At this point, we are going with the original suggestion.
    # If the suggested label is autogenerated then register it as an
    # autogenerated label.
    if lmd.is_autogenerated:
        autogenerated_labels.add(lmd.name)

    return lmd

def get_final_label(runtime_addr, binary_addr, move_id, *, binary_addr_type: BinaryAddrType):
    """Create a final label name for the given location.

    Returns the final label name

    (The name chosen by label_maker(): a string, or an expression.) A
    simple name is also added to the label as an explicit name for its
    move, so that it's defined in the output, and so that the next
    suggest_label_name() for the label finds it. Only used once tracing is
    done: LabelRef calls it the first time a reference is turned into
    text."""
    assert session.current().cpu.trace_done
    assert memorymanager.is_valid_runtime_addr(runtime_addr)
    assert memorymanager.is_valid_binary_addr(binary_addr)
    assert move_id is None or movemanager.is_valid_move_id(move_id)
    lmd = label_maker(runtime_addr, binary_addr, move_id, binary_addr_type)
    if is_simple_name(lmd.name):
        # (Noting whether it's the address's optional label's name)
        optional_label = session.current().disassembly.optional_labels.get(runtime_addr)
        from_optional_label = optional_label is not None and lmd.name == optional_label.name
        session.current().labels.labels[runtime_addr].add_explicit_name(lmd.name, lmd.defined_in_move_id, is_autogenerated=lmd.is_autogenerated, from_optional_label=from_optional_label)

    return lmd.name

def fix_label_names(*, include_annotations=False):
    """Choose the names for the labels used by the classifications so far
    (instructions and data), in address order.

    get_label() returns LabelRef objects so we can defer choosing label
    names until we've finished the tracing process. This names each label
    referred to by an instruction or data item (in the order they would be
    output), so that we have a full set of label definitions ready to emit.

    This is done twice (see go(), and stages 3 and 4 in the module
    docstring): first after tracing, and then again once everything is
    classified, with include_annotations, to name the labels used by data
    classified since (e.g. strings) and by comments and other annotations.
    (Labels named the first time keep their names.)

    After that, making the output only has to decide where label definitions
    go (see emit()). The one kind of label still named then is one that a
    definition is placed relative to: a label inside a multi-byte
    classification (e.g. at an instruction's operand) is defined as e.g.
    'l1235 = c1234+1', relative to a label at the start of the
    classification, which may need a name. Whether that's needed depends on
    which move the definition is output in, and on whether it has already
    been output, which are only known while the output is made.
    """

    assert session.current().cpu.trace_done

    # The annotations at each binary address
    annotations_at = collections.defaultdict(list)
    if include_annotations:
        annotations = session.current().disassembly.annotations
        for binary_loc in sorted(annotations, key=lambda loc: (loc.binary_addr, loc.move_id)):
            annotations_at[int(binary_loc.binary_addr)].extend(annotations[binary_loc])

    # (Only the loaded data can be classified, so just loop over that. Plain
    # integer addresses are used for speed.)
    binary_addr = 0
    for range_start, range_end in memorymanager.loaded_ranges():
        binary_addr = max(binary_addr, range_start)
        while binary_addr < range_end:
            c = classification.get_classification(binary_addr)
            if c is not None:
                move_id = session.current().moves.move_id_for_binary_addr[binary_addr]
                if include_annotations:
                    for i in range(c.length()):
                        for annotation in annotations_at.get(binary_addr + i, ()):
                            annotation.name_labels()
                if not (binary_addr in session.current().classifications.include_binary_files):
                    for line in c.as_lines(movemanager.BinaryLocation(BinaryAddr(binary_addr), move_id), None):
                        line.name_labels()
                binary_addr += c.length()
            else:
                binary_addr += 1


def calculate_move_ranges():
    """Calculate contiguous memory ranges with a shared move ID.

    As a list of (start, end) binary addresses, 'end' exclusive, in address
    order: each a run of loaded data in one move. Together they cover all
    the loaded data. emit() outputs each range in turn, a moved one in a
    block of its own."""

    move_ranges = []
    current_range_start = None
    current_range_end = None
    current_range_move_id = None
    move_id_for_binary_addr = session.current().moves.move_id_for_binary_addr
    for start_addr, end_addr in sorted(session.current().memory.load_ranges):
        binary_addr = start_addr
        while binary_addr < end_addr:
            if current_range_start is not None:
                if (binary_addr == current_range_end and move_id_for_binary_addr[binary_addr] == current_range_move_id):
                    current_range_end = binary_addr + 1
                else:
                    move_ranges.append((current_range_start, current_range_end))
                    current_range_start = None
            if current_range_start is None:
                current_range_start = binary_addr
                current_range_end = binary_addr + 1
                current_range_move_id = move_id_for_binary_addr[binary_addr]
            binary_addr += 1

    if current_range_start != current_range_end:
        move_ranges.append((current_range_start, current_range_end))

    return move_ranges

def constant_value_to_string(value, format):
    """Convert the given value of a constant, return the string value used to define the constant as specified by the format parameter

    'format' is a Format. DEFAULT is decimal or hex, as
    config.set_constants_are_decimal() says (or STRING, for a string
    value). DECIMAL_SIGNED takes the value to be a signed byte (128 to 255
    are -128 to -1). BINARY and PICTURE_BINARY give 8 bits for a value from
    0 to 255, otherwise 16. STRING and CHAR put the value in double or
    single quotes."""

    # If given a string with no format specified, treat it as a string
    if isinstance(value, str) and (format == Format.DEFAULT):
        format = Format.STRING

    if (format == Format.DECIMAL) or ((format == Format.DEFAULT) and config.get_constants_are_decimal()):
        return str(value)
    elif format == Format.DECIMAL_SIGNED:
        return str(value) if value<128 else str(value-256)
    elif (format == Format.HEX) or ((format == Format.DEFAULT) and not config.get_constants_are_decimal()):
        formatter = config.get_assembler()
        return formatter.hex(value)
    elif format == Format.BINARY:
        formatter = config.get_assembler()
        return mainformatter.binary_formatter(value, 8 if ((value >= 0) and (value < 256)) else 16)
    elif format == Format.PICTURE_BINARY:
        formatter = config.get_assembler()
        return mainformatter.picture_binary_formatter(value, 8 if ((value >= 0) and (value < 256)) else 16)
    elif format == Format.STRING:
        formatter = config.get_assembler()
        return str('"' + value + '"')
    assert format == Format.CHAR, "unknown format {0}".format(format)
    return str("'" + value + "'")

def sorted_constants():
    """The constants, in the order they're output (natural sort order of
    their names)."""
    convert = lambda text: int(text) if text.isdigit() else text.lower()
    alphanum_key = lambda key: [convert(c) for c in re.split('([0-9]+)', key.name)]
    return sorted(session.current().disassembly.constants, key=alphanum_key)

def effective_memory_regions():
    """The memory regions in effect (see memory_region_for()): the CPU's,
    then those named by acorn.py or the control file, with each range named
    as it was last named, and those named "" left out. As (start, end, name),
    by start address, larger first. (For the JSON output.)"""
    cpu = session.current().cpu
    regions = (cpu.memory_regions() if cpu is not None else []) + session.current().disassembly.memory_regions
    names = {}
    for start, end, name in regions:
        names[(start, end)] = name
    return sorted(((start, end, name) for (start, end), name in names.items() if name != ""),
                  key=lambda r: (r[0], -(r[1] - r[0])))

def emit_constants():
    """The constant definitions, as a list of line objects (see output.py).

    Under the heading 'Constants', in sorted_constants() order, as 'name =
    value' with the '=' signs and the inline comments lined up (each column
    rounded up to a whole number of indents). Each constant's comment goes
    where its 'align' says: on the line before, inline, or on the line
    after. Empty if there are no constants."""
    constants = session.current().disassembly.constants
    lines = []

    if len(constants) == 0:
        return lines

    # Length of indent string
    indent_len = len(config.get_indent_string())

    lines.append(output.CommentLine("Constants").resolve())

    # We want to align the equals symbols in the list of constants, so
    # we find the longest name. Add one to allow for a space after the name
    max_name_len = max(len(c.name)+1 for c in constants)
    max_name_len  = utils.round_up(max_name_len, indent_len)    # Round up to next indent level

    # Similarly, get the longest value as a string so we can align the comments
    # so that we can align the inline comments.
    max_value_len = max(len(constant_value_to_string(c.value, c.format)) for c in constants)

    # Comment column is after 'name = value'
    comment_column = max_name_len + 3 + max_value_len
    comment_column = utils.round_up(comment_column, indent_len) # Round up to next indent level

    for c in sorted_constants():
        value = constant_value_to_string(c.value, c.format)

        # output a comment on the line before the definition (if there's a
        # comment: 'align' can be given without one)
        if c.comment and ((c.align == Align.BEFORE_LINE) or (c.align == Align.BEFORE_LABEL)):
            lines.append(output.Comment(c.comment, indent=0).resolve())

        # output the definition with an optional inline comment
        lines.append(output.ConstantDefinition(c.name, value, max_name_len,
            c.comment if c.align == Align.INLINE else None, comment_column).resolve())

        # output a comment on the line after the definition (if there's one)
        if c.comment and ((c.align == Align.AFTER_LINE) or (c.align == Align.AFTER_LABEL)):
            lines.append(output.Comment(c.comment, indent=0).resolve())
    lines.append(output.Blank().resolve())
    return lines

def emit(print_output=True):
    """Outputs the disassembly.

    i.e. makes the whole output and returns it as text. (This is the last
    stage of go(), stage 5 in the module docstring, once everything is
    classified and the labels are named. 'print_output' isn't used: go()
    prints the text.)

    The output is built as a list of line objects (see output.py), each
    resolved as it's made (naming any labels used for the first time, and
    choosing which label definitions go where), in output order. Then the
    lines are rendered and joined to make the text.

    It's made in three parts: the header (the assembler's prologue, the
    constants, and the "Memory locations" list), the main disassembly, and
    the footer (the assembler's epilogue, e.g. assertions, then tables of
    label references, auto-generated labels and statistics). The main
    disassembly is made first, since the "Memory locations" list has the
    names that it didn't define inline."""

    autogenerated_labels = session.current().disassembly.autogenerated_labels
    formatter = config.get_assembler()
    session.current().disassembly.output_items = []
    session.current().disassembly.output_range_boundaries = []

    # The lines at the start: the prologue, the constants and the labels
    # that aren't defined in the main disassembly
    header = []

    # All the labels are named now, so expressions can be evaluated
    classification.prepare_expression_checks()

    # Output any prologue
    header.append(output.Directive("disassembly_start").resolve())

    # Length of indent string
    indent_len = len(config.get_indent_string())

    # Emit constants first
    header.extend(emit_constants())

    # For debugging py8dis output all labels, their addresses and move_ids
    if config.get_show_all_labels():
        header.append(output.Text(labelmanager.all_labels_as_comments()).resolve())

    # Break the output down into sub-ranges which share the same move
    # ID. We completely ignore the classifications here; moves are more
    # important and can bisect a classification. We call isolate_range
    # to fix up the classifications afterwards.
    move_ranges = calculate_move_ranges()

    for start_addr, end_addr in move_ranges:
        isolate_range(start_addr, end_addr)

    # Generate the disassembly proper, but don't emit it just yet. We
    # do this so we can emit label definitions in the "best" move
    # region and then emit any leftover labels as explicit definitions
    # below.

    # d is the main disassembly output (a list of line objects).
    d = []

    def record_emit_point(binary_addr, move_id):
        """Record that labels for the move can be defined inline at the
        binary address (at its runtime address in that move)."""
        md = session.current().moves.move_definitions[move_id]
        runtime_addr = md.convert_binary_to_runtime_addr(binary_addr)
        labelmanager.notify_emit_opportunity(runtime_addr, move_id)

    # Calculate the move_ids that will emit output?
    # (i.e. record, before anything is output, where each move's labels can
    # be defined inline: at every address of each range and just after its
    # end, in its move, and for a moved range, in the base move just before
    # and after its block. See Label.gather_inline_label_definitions(),
    # which uses these to define labels for a move that isn't output at
    # their address somewhere else.)
    for start_addr, end_addr in move_ranges:
        move_id = session.current().moves.move_id_for_binary_addr[start_addr]
        if move_id != movemanager.BASE_MOVE_ID:
            record_emit_point(start_addr, movemanager.BASE_MOVE_ID)

        addr = start_addr
        while addr < end_addr:
            for i in range(0, classification.get_classification(addr).length()):
                record_emit_point(addr + i, move_id)
            addr += classification.get_classification(addr).length()
        assert addr == end_addr
        record_emit_point(end_addr, move_id)
        if move_id != movemanager.BASE_MOVE_ID:
            record_emit_point(end_addr, movemanager.BASE_MOVE_ID)

    # Output disassembly for each range in turn
    old_end_addr = None
    for start_addr, end_addr in move_ranges:
        if old_end_addr is None:
            # A PRG file's two-byte header (its load address), if it was
            # loaded with load_prg(), or an ATM file's 22-byte header, if it
            # was loaded with load_atm(), so the output assembles to the
            # whole file
            file_header = memorymanager.file_header()
            if file_header is not None and file_header.loaded_file.prg:
                if config.get_assembler().prg_header(file_header.load_addr) is None:
                    utils.warn("the PRG file's load address isn't output with this assembler, so the output assembles to the data without it")
                else:
                    d.append(output.Directive("prg_header", file_header.load_addr).resolve())
            elif file_header is not None:
                atm = file_header.loaded_file.atm
                if config.get_assembler().atm_header(file_header.load_addr, atm) is None:
                    utils.warn("the ATM file's header isn't output with this assembler, so the output assembles to the data without it")
                else:
                    d.append(output.Directive("atm_header", file_header.load_addr, atm).resolve())
            # Output an ORG at the beginning
            d.append(output.Directive("code_start", start_addr, end_addr, True).resolve())
            old_end_addr = start_addr

        move_id = session.current().moves.move_id_for_binary_addr[start_addr]

        # Handle start of a new !pseudopc block
        if move_id != movemanager.BASE_MOVE_ID:
            # (A gap before it, e.g. when it's another file loaded elsewhere,
            # needs a new ORG first, as for code that isn't moved)
            if start_addr != old_end_addr:
                d.append(output.Directive("code_start", start_addr, end_addr, False, old_end_addr).resolve())

            # Output any base move labels just before starting a new !pseudopc block
            d.extend(emit_labels(BinaryLocation(start_addr, movemanager.BASE_MOVE_ID), False))

            # Output start of !pseudopc block
            dest_runtime_addr = movemanager.b2r(start_addr)
            block_title = "Move {0}: {1} to {2} for length {3}".format(move_id, config.get_assembler().hex(start_addr), config.get_assembler().hex(dest_runtime_addr), end_addr - start_addr)
            d.append(output.Blank().resolve())
            d.append(output.Comment(block_title, 0).resolve())
            pseudopc_args = (dest_runtime_addr, start_addr, end_addr - start_addr, move_id)
            d.append(output.Directive("pseudopc_start", *pseudopc_args).resolve())
        else:
            # If a new ORG is needed, output that
            if start_addr != old_end_addr:
                d.append(output.Directive("code_start", start_addr, end_addr, False, old_end_addr).resolve())

        # output at each address within the block
        was_code = None
        addr = start_addr
        while addr < end_addr:
            # if we have just transitioned from data to code, add a blank line
            now_is_code = classification.is_code(addr)
            if now_is_code and was_code == False:
                d.append(output.Blank().resolve())
            was_code = now_is_code

            if addr in session.current().classifications.include_binary_files:
                # output an included binary
                inc_binary_filepath = session.current().classifications.include_binary_files[addr]
                directive = output.Directive("include_binary_file", inc_binary_filepath).resolve()
                d.append(directive)
                session.current().disassembly.output_items.append((BinaryLocation(addr, move_id), classification.get_classification(addr), [directive]))
            else:
                # output the line itself
                d.extend(emit_addr(BinaryLocation(addr, move_id)))

            # move to the next address
            addr += classification.get_classification(addr).length()
        assert addr == end_addr

        # Emit labels at the end address of the move range
        d.extend(emit_labels(BinaryLocation(end_addr, move_id), True))

        # Handle the end of the !pseudopc block
        if move_id != movemanager.BASE_MOVE_ID:
            # Output the end of the !pseudopc block
            pseudopc_args = (movemanager.b2r(start_addr), start_addr, end_addr - start_addr, move_id)
            d.append(output.Directive("pseudopc_end", *pseudopc_args).resolve())

            # Output any base move labels after the !pseudopc block is done
            d.extend(emit_labels(BinaryLocation(end_addr, movemanager.BASE_MOVE_ID), False))
        old_end_addr = end_addr

    # Emit labels which haven't been emitted inline with the disassembly.
    # (The heading is only output if there are any.) These go in the header,
    # before the main disassembly.
    definitions = memory_location_definitions(indent_len)
    if definitions:
        header.append(output.CommentLine("Memory locations").resolve())
        header.extend(definitions)

    # The lines at the end: the assertions, and tables of information
    footer = []

    # Finish off disassembly (the assembler's epilogue, e.g. beebasm's
    # 'save', and the assertions)
    footer.append(output.Blank().resolve())
    footer.append(output.Directive("disassembly_end").resolve())

    # Show label reference frequency table
    if config.get_label_references():
        footer.append(output.Text(session.current().cpu.add_reference_frequency_table()).resolve())

    # Show auto-generated labels
    if config.get_show_autogenerated_labels():
        if len(autogenerated_labels) > 0:
            footer.append(output.Blank().resolve())
            footer.append(output.CommentLine("Automatically generated labels:").resolve())
            for label in sorted(autogenerated_labels):
                footer.append(output.CommentLine("    {0}".format(label)).resolve())

    # Show stats
    if config.get_show_stats():
        footer.append(output.Blank().resolve())
        stats = classification.get_stats()

        total = stats.num_code_bytes + stats.total_data()
        code_percent = round((100 * stats.num_code_bytes) / total)
        data_percent = 100-code_percent
        for text in ["Stats:",
                     "",
                     "    Total size (Code + Data) = {0} bytes".format(total),
                     "    Code                     = {0} bytes ({1}%)".format(stats.num_code_bytes, code_percent),
                     "    Data                     = {0} bytes ({1}%)".format(stats.total_data(), data_percent),
                     "",
                     "    Number of instructions   = {0}".format(stats.num_instructions),
                     "    Number of data bytes     = {0} bytes".format(stats.num_data_bytes),
                     "    Number of data words     = {0} bytes".format(stats.num_data_words),
                     "    Number of string bytes   = {0} bytes".format(stats.num_string_bytes),
                     "    Number of strings        = {0}".format(stats.num_strings)]:
            footer.append(output.CommentLine(text).resolve())
        footer.append(output.Blank().resolve())

    # The whole document: the header, then the main disassembly, then the
    # footer. The main disassembly starts with a blank line (before its first
    # 'org'), so any blank lines at the end of the header are left out, as are
    # blank lines at the very start.
    header_text = [str(line) for line in output.render_lines(header)]
    while header_text and header_text[-1] == "":
        header_text.pop()
    text = header_text + [str(line) for line in output.render_lines(d + footer)]
    while text and text[0] == "":
        text.pop(0)
    text = formatter.tidy_output(text)

    # Join all lines of output
    result = "\n".join(formatter.sanitise_line(line) for line in text)

    # Return the assembly listing
    return result

def add_memory_region(start_addr, end_addr, name):
    """Name a region of memory, from start_addr up to (but not including)
    end_addr. The "Memory locations" list at the top of the output is grouped
    by region. (Where regions overlap, the smallest one containing an address
    is used, or of two the same size the one added last. An empty name
    removes the region with that range. See memory_region_for().)"""
    session.current().disassembly.memory_regions.append((int(start_addr), int(end_addr), name))

def memory_region_for(runtime_addr):
    """The (start, end, name) of the region containing the address (see
    add_memory_region()), or None. Where regions overlap, the smallest one
    containing the address is used, so e.g. a region the control file names
    within zero page takes precedence over zero page itself. Of two the same
    size, the one named last is used, so naming a region again renames it:
    the CPU's regions (e.g. the 6502's zero page and stack) count as named
    first, then those named by acorn.py or the control file, in order.

    Naming a range "" removes the region with that range, so its labels go in
    the next larger region that contains them (or none)."""
    cpu = session.current().cpu
    regions = (cpu.memory_regions() if cpu is not None else []) + session.current().disassembly.memory_regions

    # The name of each range containing the address, as last named (in the
    # order they were last named)
    names = {}
    for start, end, name in regions:
        if start <= runtime_addr < end:
            names.pop((start, end), None)
            names[(start, end)] = name

    result = None
    for (start, end), name in names.items():
        if name != "" and (result is None or end - start <= result[1] - result[0]):
            result = (start, end, name)
    return result

def _range_heading(label):
    """The heading of the ranges with optional labels of their own (see
    add_range_optional_labels()) that the label is used in, if it's used
    only in such ranges, all with the same heading, else None. Such a label
    is listed under that heading, rather than under its memory region's:
    e.g. an address that only a C64 program's drive code uses, with no 1541
    name, is the drive's, so it goes under '1541 drive', not under the C64's
    region for the address."""
    ranges = [r for r in session.current().disassembly.range_optional_labels if r.heading is not None]
    if not ranges or not label.references:
        return None
    heading = None
    for reference in label.references:
        r = next((r for r in ranges if r.start_addr <= reference.binary_addr < r.end_addr), None)
        if r is None or (heading is not None and r.heading != heading):
            return None
        heading = r.heading
    return heading

def memory_location_definitions(indent_len):
    """The 'name = value' definitions of the labels not defined in the main
    disassembly, as a list of line objects (see output.py): in address order,
    grouped by memory region (see add_memory_region()), each group with a
    heading and its own alignment. (With config.set_memory_region_headings(False)
    they're one list, as without any regions.)

    Called by emit() once the main disassembly is made, so the names left
    to define are those that weren't defined inline (see
    Label.gather_explicit_definitions(), which marks them as defined). The
    local labels with a heading of their own come after the regions, under
    that heading. Each label's heading is also recorded, for the JSON
    output."""

    labels = session.current().labels.labels
    formatter = config.get_assembler()
    headings = session.current().disassembly.memory_location_headings

    # The names to define for each label, grouped by region (in address
    # order), then the local labels with a heading of their own (see
    # Label.LocalLabelName), and the labels used only in a range with a
    # heading of its own (see _range_heading()), grouped by heading (in the
    # order they come)
    groups = []         # (region, [(label, names)])
    own_headings = {}   # heading: [(label, names)]
    use_regions = config.get_memory_region_headings()
    for addr in sorted(labels):
        label = labels[addr]
        names = label.gather_explicit_definitions()
        local_headings = label.local_label_headings() if use_regions else {}
        for name in names:
            if name in local_headings:
                own_headings.setdefault(local_headings[name], []).append((label, [name]))
        names = [name for name in names if name not in local_headings]
        if not names:
            continue
        range_heading = _range_heading(label) if use_regions else None
        if range_heading is not None:
            own_headings.setdefault(range_heading, []).append((label, names))
            headings[int(label.runtime_addr)] = range_heading
            continue
        region = memory_region_for(addr) if use_regions else None
        if not groups or groups[-1][0] != region:
            groups.append((region, []))
        groups[-1][1].append((label, names))
    for heading, definitions in own_headings.items():
        groups.append((heading, definitions))

    # Without any regions (e.g. for the 8080, unless the control file names
    # some), or with the headings turned off, there's just the one list
    use_headings = any(region is not None for region, _ in groups)

    lines = []
    for region, definitions in groups:
        if use_headings:
            if region is None:
                heading = "Other"
            elif isinstance(region, str):
                # (A heading of its own)
                heading = region
            else:
                start, end, name = region
                heading = "{0} ({1}-{2})".format(name, formatter.hex4_for_comment(start), formatter.hex4_for_comment(end - 1))
            lines.append(output.Blank().resolve())
            lines.append(output.CommentLine(heading).resolve())
            for label, _ in definitions:
                if not isinstance(region, str):
                    headings[int(label.runtime_addr)] = "Other" if region is None else region[2]

        # Align the values (rounded up to the next indent level)
        align = max(len(name) for _, names in definitions for name in names)
        align = indent_len * ((align + indent_len - 1) // indent_len)
        for label, names in definitions:
            lines.append(output.ExplicitLabelDefinitions(label, names, align).resolve())
    return lines

# It's possible (but unlikely) there is a multi-byte classification straddling the
# ends of our range; if so, split them so we can output the precise range wanted.
def isolate_range(start_addr, end_addr):
    """If a move boundary is in the middle of an instruction etc, then
    split the classification.

    (At the binary addresses start_addr and end_addr, with a warning, see
    classification.split_classification().)"""

    classification.split_classification(start_addr, warn=True)
    classification.split_classification(end_addr, warn=True)

def emit_labels(binary_loc, output_annotations, at_boundary=True):
    """Emit labels and non-inline annotations for the given address, as a
    list of line objects (see output.py). 'at_boundary' is True for the
    labels at the start or end of a range of the output (rather than for an
    item, see emit_addr()), which are recorded for the JSON output.

    The label definitions are those of the label at the binary location's
    runtime address (in its move) that can be defined inline and haven't
    been yet. With 'output_annotations', the annotations at the binary
    location that go before the label come first, and those that go after
    it come after."""

    annotations = session.current().disassembly.annotations
    binary_loc = movemanager.make_binloc(binary_loc)

    if at_boundary:
        session.current().disassembly.output_range_boundaries.append((binary_loc, output_annotations))

    result = []
    md = session.current().moves.move_definitions[binary_loc.move_id]
    runtime_addr = md.convert_binary_to_runtime_addr(binary_loc.binary_addr)

    if output_annotations:
        for annotation in utils.sorted_annotations(binary_loc, annotations[binary_loc]):
            if annotation.align == Align.BEFORE_LABEL:
                result.append(output.AnnotationLine(annotation, binary_loc.binary_addr).resolve())

    result.append(output.InlineLabelDefinitions(session.current().labels.labels[runtime_addr], runtime_addr, binary_loc).resolve())

    if output_annotations:
        for annotation in utils.sorted_annotations(binary_loc, annotations[binary_loc]):
            if annotation.align == Align.AFTER_LABEL:
                result.append(output.AnnotationLine(annotation, binary_loc.binary_addr).resolve())
    return result

def emit_addr(binary_loc):
    """Emit labels, the output for the classification, any remaining
    annotations in the range of the classification, as a list of line
    objects (see output.py).

    For the classification at the binary location, in this order: the
    labels at its address with their annotations (see emit_labels()), the
    definitions of labels at addresses inside it (relative to its start,
    e.g. 'l1235 = c1234+1'), the annotations before the line, the
    classification's own lines (with any inline comments), the annotations
    after the line, then the other annotations at addresses inside it. It's
    also recorded for the JSON output."""
    annotations = session.current().disassembly.annotations
    result = []
    classification_length = classification.get_classification(binary_loc.binary_addr).length()

    # We queue up labels defined "within" a multi-byte classification first
    # because we might need to create a new label at binary_loc.binary_addr
    # to help in defining them.
    pending_labels = []
    for i in range(1, classification_length):
        runtime_addr = movemanager.b2r(binary_loc.binary_addr + i)
        if runtime_addr in session.current().labels.labels:
            if session.current().labels.labels[runtime_addr].definable_inline:
                pending_labels.append(output.InlineLabelDefinitions(session.current().labels.labels[runtime_addr], movemanager.b2r(binary_loc.binary_addr), binary_loc).resolve())

    # Emit label definitions for this address.
    result.extend(emit_labels(binary_loc, True, at_boundary=False))

    # Emit any label definitions for addresses within the classification.
    result.extend(pending_labels)

    # Emit any annotations before outputting the line itself
    for annotation in utils.sorted_annotations(binary_loc, annotations[binary_loc]):
        if annotation.align == Align.BEFORE_LINE:
            result.append(output.AnnotationLine(annotation, binary_loc.binary_addr).resolve())

    # Emit the classification itself.
    c = classification.get_classification(binary_loc.binary_addr)
    lines = output.resolve(c.as_lines(binary_loc, annotations))
    result.extend(lines)
    session.current().disassembly.output_items.append((binary_loc, c, lines))

    # Emit any annotations after outputting the line itself
    for annotation in utils.sorted_annotations(binary_loc, annotations[binary_loc]):
        if annotation.align == Align.AFTER_LINE:
            result.append(output.AnnotationLine(annotation, binary_loc.binary_addr).resolve())

    # Emit any annotations which would fall within the classification.
    # We do this after the classification itself; this does have some
    # logic (we're "rounding to the end of the classification") and in
    # particular this works better than "rounding to start" does with
    # the current way overlapping instructions are emitted as comments.
    for i in range(1, classification_length):
        binary_loc = BinaryLocation(binary_loc.binary_addr + 1, binary_loc.move_id)

        for annotation in utils.sorted_annotations(binary_loc, annotations[binary_loc]):
            if annotation.align != Align.INLINE:
                result.append(output.AnnotationLine(annotation, binary_loc.binary_addr).resolve())

    return result
